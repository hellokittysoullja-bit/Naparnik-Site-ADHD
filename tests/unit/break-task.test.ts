import { describe, expect, it } from 'vitest'
import { breakable, BREAK_MIN } from '@/lib/break-task'
import { parseBreakdownAnswer, parsePlan, PLAN_MAX } from '@/lib/ai/agents/breakdown'

// 16.11: одно правило разламывания на весь продукт (Дом, Фокус, «Дела», «Не могу начать», сервер)
describe('breakable', () => {
  it('понятное короткое дело разламывается, порог тот же, что у сервера', () => {
    expect(BREAK_MIN).toBe(3)
    for (const t of ['пол', 'почта', 'Курсовая по логистике', '  отчёт  ']) expect(breakable(t)).toBe(true)
  })
  it('то, что нечем разламывать, — нет', () => {
    for (const t of ['', '  ', 'Hh', 'ок', '2+2', '...', '1 2 3']) expect(breakable(t)).toBe(false)
  })
})

describe('parseBreakdownAnswer', () => {
  it('«?» модели — дело не понято, а не шаги', () => {
    for (const t of ['?', ' ? ', '«?»', '**?**']) expect(parseBreakdownAnswer(t)).toEqual({ kind: 'unclear' })
  })
  it('три шага с оценками — шаги', () => {
    expect(parseBreakdownAnswer('Открыть почту | 1\nНайти письмо | 2\nОтветить фразой | 3')).toEqual({
      kind: 'steps',
      steps: ['Открыть почту', 'Найти письмо', 'Ответить фразой'],
      minutes: [1, 2, 3],
      source: 'model',
    })
  })
  it('вопрос внутри текста — не «не понял»', () => {
    expect(parseBreakdownAnswer('Что именно висит?')).toBeNull()
  })
})

// 16.11, владелец: «разбивка как у goblin.tools» — весь путь до конца дела, а не три шага на старт
describe('parsePlan', () => {
  it('план до конца: все шаги, минуты, «пока ждёшь», без нумерации и вступления', () => {
    const text = [
      'Вот план:',
      '1. Собрать грязное бельё в корзину | 3',
      '2. Загрузить бельё в машинку | 2',
      '3. Засыпать порошок и включить стирку | 2',
      '4. Пока ждёшь: протереть полку в ванной | 5',
      '5. Развесить бельё на сушилке | 10',
      '6. Сложить сухое бельё в шкаф | 10',
    ].join('\n')
    expect(parseBreakdownAnswer(text)).toEqual({
      kind: 'steps',
      steps: [
        'Собрать грязное бельё в корзину',
        'Загрузить бельё в машинку',
        'Засыпать порошок и включить стирку',
        'Протереть полку в ванной',
        'Развесить бельё на сушилке',
        'Сложить сухое бельё в шкаф',
      ],
      minutes: [3, 2, 2, 5, 10, 10],
      wait: [false, false, false, true, false, false],
      source: 'model',
    })
  })
  it('больше 12 шагов обрезается, повтор — один раз, меньше двух — негодно', () => {
    const many = Array.from({ length: 15 }, (_, i) => `Сделать шаг номер ${i + 1}`).join('\n')
    expect(parsePlan(many)?.steps).toHaveLength(PLAN_MAX)
    expect(parsePlan('Открыть файл\nОткрыть файл\nНаписать заголовок\nСохранить')?.steps).toEqual(['Открыть файл', 'Написать заголовок', 'Сохранить'])
    expect(parsePlan('Открыть файл')).toBeNull()
    expect(parsePlan('Опустить веки | 1\nПоднять веки | 1')?.steps).toEqual(['Опустить веки', 'Поднять веки'])
  })
  it('абзац вместо шага — негодный ответ (уйдёт следующей модели)', () => {
    expect(parsePlan('Открыть файл\nСначала очень внимательно прочитай всё задание целиком от начала до конца и подумай над каждым его пунктом отдельно\nСохранить')).toBeNull()
    expect(parsePlan('Взять пакет для мусора и собрать весь крупный мусор с пола | 3\nПротереть пыль | 5\nВымыть пол | 10')?.steps).toHaveLength(3)
  })
})

describe('parsePlan: живые прогоны 16.11', () => {
  it('«Пока ждёшь закипания воды:» и «Пока стирается:» — шаг-ожидание', () => {
    const p = parsePlan('Налить воду в кастрюлю | 1\nПока ждёшь закипания воды: убрать мусор со стола | 2\nПока стирается: протереть полку | 3')
    expect(p?.steps).toEqual(['Налить воду в кастрюлю', 'Убрать мусор со стола', 'Протереть полку'])
    expect(p?.wait).toEqual([false, true, true])
  })
  it('обрывок ответа («На», «Раз» последним шагом) — весь ответ негоден', () => {
    expect(parsePlan('Найти место | 1\nВзять презерватив | 1\nНа')).toBeNull()
    expect(parsePlan('Найти место | 1\nРаздеться | 1\nЗаняться сексом | 15')?.steps).toHaveLength(3)
  })
  it('«| 10080» не остаётся хвостом в тексте шага; опечатка «Лчь» исправляется', () => {
    const p = parsePlan('Лчь на диван | 1\nВзвешиваться раз в неделю | 10080\nЗаписать вес | 1')
    expect(p?.steps).toEqual(['Лечь на диван', 'Взвешиваться раз в неделю', 'Записать вес'])
    expect(p?.minutes).toEqual([1, undefined, 1])
  })
  it('строка «Итог:» в ответе не становится шагом', () => {
    expect(parsePlan('Итог: бельё в шкафу\nСобрать бельё | 2\nЗапустить стирку | 1\nРазвесить бельё | 5')?.steps[0]).toBe('Собрать бельё')
  })
})

it('короткие целые глаголы одним словом — годные шаги («Лечь», «Сесть», «Встать»)', () => {
  expect(parsePlan('Сесть | 1\nЛечь | 1\nВстать | 1')?.steps).toEqual(['Сесть', 'Лечь', 'Встать'])
})

it('«тряпки» в шаге уборки — не стыд; «ты тряпка» — стыд', async () => {
  const { checkOutput } = await import('@/lib/ai/guards/output')
  expect(checkOutput('Положить на пол старые тряпки и полотенца | 2', { maxChars: 500 })).toEqual({ ok: true })
  expect(checkOutput('Ну ты тряпка, соберись', { maxChars: 500 }).ok).toBe(false)
  expect(checkOutput('Тряпка ты, а не человек', { maxChars: 500 }).ok).toBe(false)
})

it('смех и возгласы — дело «посмеяться», обычные дела не трогаются', async () => {
  const { asTask } = await import('@/lib/ai/agents/breakdown')
  for (const t of ['хахахаха', 'Ахахах', 'лол', 'ЛООЛ', 'кек', 'ору', 'ржу', 'хаха!', 'lol']) expect(asTask(t)).toBe('посмеяться')
  for (const t of ['хата', 'убрать в хате', 'холодильник', 'ах да, почта', 'Hh']) expect(asTask(t)).toBe(t)
})
