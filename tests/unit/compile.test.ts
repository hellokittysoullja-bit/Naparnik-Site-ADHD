import { describe, expect, it } from 'vitest'
import { compile } from '@/lib/ai/agents/compile'

/** Компилятор (22.11, как Compiler у goblin.tools, без модели; сверка — research/31-compiler) */
describe('компилятор: поток мыслей → дела', () => {
  it('разговорное счищено, глагол вперёд, «посуда стоит» — дело из базы', () => {
    expect(compile('блин надо отчёт доделать, ещё к врачу записаться, а, и маме позвонить, посуда со вчера стоит, и кота покормить не забыть, ну и наверное спортом заняться хоть когда-нибудь'))
      .toEqual(['Доделать отчёт', 'Записаться к врачу', 'Позвонить маме', 'Помыть посуду', 'Покормить кота', 'Заняться спортом'])
  })
  it('жалобы → действие, падеж: «квартплата не оплачена» → «Оплатить квартплату»', () => {
    expect(compile('у меня куча всего: квартплата не оплачена, интернет отключат если не заплачу, и ещё штраф пришёл')).toEqual(['Оплатить квартплату', 'Оплатить интернет', 'Оплатить штраф'])
    expect(compile('кот блевал, надо к ветеринару, и наполнитель кончился')).toEqual(['Сходить к ветеринару', 'Купить наполнитель'])
  })
  it('рассказ о других и чувства — не дела; «подарок не купил» → «Купить подарок»', () => {
    expect(compile('мама просила помочь с переездом в субботу, а ещё у Лены день рождения, подарок не купил')).toEqual(['Помочь с переездом в субботу', 'Купить подарок'])
    expect(compile('мне плохо, ничего не хочу, но надо хотя бы помыться и поесть')).toEqual(['Помыться', 'Поесть'])
    expect(compile('ничего не успеваю, работа, учёба, дом, всё горит')).toEqual([])
  })
  it('местоимение — тот, о ком шла речь; голый глагол со списком — одно дело; сроки остаются', () => {
    expect(compile('нужно записать ребёнка в бассейн, купить ему кроссовки и подписать дневник')).toEqual(['Записать ребёнка в бассейн', 'Купить ребёнку кроссовки', 'Подписать дневник'])
    expect(compile('продать старый велик на авито, сфоткать его сначала')).toEqual(['Продать старый велик на Авито', 'Сфоткать старый велик'])
    expect(compile('надо купить: хлеб, сыр, колбасу')).toEqual(['Купить хлеб, сыр, колбасу'])
    expect(compile('короче сегодня надо купить продукты, молоко хлеб яйца, потом забрать посылку с озона')).toEqual(['Купить продукты (молоко, хлеб, яйца)', 'Забрать посылку с Озона'])
    expect(compile('сделать презентацию к пятнице, созвониться с заказчиком')).toEqual(['Сделать презентацию к пятнице', 'Созвониться с заказчиком'])
  })
  it('своё слово, которого нет в базе, не теряется; «и» внутри дела не режет его', () => {
    expect(compile('Хрюндель, Фыва')).toEqual(['Хрюндель', 'Фыва'])
    expect(compile('позвонить маме и папе')).toEqual(['Позвонить маме и папе'])
    expect(compile('отчёт для Марины, записаться на стрижку, ещё оплатить интернет')).toEqual(['Отчёт для Марины', 'Записаться на стрижку', 'Оплатить интернет'])
  })
})
