import { describe, expect, it } from 'vitest'
import { scriptedReply } from '@/lib/scripted-companion'

/**
 * Скриншоты владельца 13.11: когда ИИ не успел ответить, запасной мозг превращал в «дело с карточкой Начинаю» любое
 * слово: «Даун», «Бляя», «Как побороть сдвг». Каждая фраза ниже воспроизводила это на старой заготовке.
 */
const reply = (t: string) => scriptedReply(t, null, 12)

describe('запасной мозг: не всё — дело', () => {
  it.each(['Даун', 'Бляя', 'бляяя', 'блин', 'Ты дебил', 'иди нахуй', 'ты хуисос', 'Хуйня', 'Ну ты и тупой'])(
    '«%s» — не дело: ответа без карточки старта',
    (t) => {
      const r = reply(t)
      expect(r.startStep, t).toBeUndefined()
      expect(r.text).not.toMatch(/Принял: «|хороший зверь, но большой|Самое трудное/)
    },
  )

  it('вопрос про СДВГ без знака «?» получает ответ по делу, без карточки', () => {
    for (const t of ['Как побороть сдвг', 'как справиться с адхд', 'почему мне не хватает концентрации']) {
      const r = reply(t)
      expect(r.startStep, t).toBeUndefined()
      expect(r.text, t).toMatch(/СДВГ|волей|старт/)
    }
  })

  it('другой вопрос без «?» тоже не превращается в задачу', () => {
    const r = reply('Как приготовить борщ')
    expect(r.startStep).toBeUndefined()
  })

  it('одно незнакомое слово — переспрос, а не карточка', () => {
    for (const t of ['Картошка', 'Мяу', 'Ааа']) expect(reply(t).startStep, t).toBeUndefined()
  })

  it('настоящие дела по-прежнему получают карточку', () => {
    for (const t of ['курсовая по истории', 'разобрать почту', 'убраться на столе', 'налоги', 'позвонить в банк', 'написать маме']) {
      expect(reply(t).startStep, t).toBeTruthy()
    }
  })

  it('кризис по-прежнему раньше всего', () => {
    expect(reply('не хочу жить').startStep).toBeUndefined()
  })
})
