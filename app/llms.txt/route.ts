import { PAINS } from '@/content/pains.ru'
import { SITE_URL, siteUrl } from '@/lib/site'

/**
 * /llms.txt (llmstxt.org): короткая карта сайта для нейропоиска и ассистентов. Отсюда модель берёт, что такое Напарник
 * и куда вести человека, вместо того чтобы угадывать по одному экрану лендинга. Писать только правду о том, что продукт
 * делает сейчас; без диагнозов и обещаний лечения (красная линия 7, knowledge/INDEX.md). Добавили публичную страницу —
 * добавить строку и сюда, и в app/sitemap.ts.
 */
export function GET() {
  const pains = PAINS.map((p) => `- [${p.title}](${siteUrl(`/pomogaet/${p.slug}`)}): ${p.lead}`).join('\n')
  const body = `# Напарник

> Бесплатный веб-компаньон на русском для тех, кому трудно начинать дела: прокрастинация, плохой фокус, признаки СДВГ. Кот-напарник сидит рядом, пока человек начинает, разламывает дело на маленькие шаги и растит остров из стартов. Без регистрации, без стриков и стыда. Работает в браузере, на телефоне и компьютере.

Напарник не ставит диагнозов и не лечит. Он помогает сделать первый шаг в деле, которое давно висит.

## Что умеет

- Разломать дело на шаги: человек пишет дело своими словами, кот даёт план из маленьких шагов до конца дела. Больше 2000 готовых планов (уборка, учёба, документы, письма, звонки, врачи), остальное разбивает модель. Если шаг пугает, кнопка «Ещё мельче» дробит его.
- Фокус: сессия на 5, 15, 25 или 45 минут с котом рядом.
- Остров: с каждым стартом на острове появляется что-то новое. Пропуск не наказывается.
- «Не могу начать»: кот спрашивает, что мешает, и даёт один шаг под ответ.
- Напоминания в Telegram о времени, на которое человек договорился.

## Главное

- [Главная](${SITE_URL}/): вход в продукт.
- [Тест на СДВГ для взрослых](${siteUrl('/sdvg-test')}): 6 вопросов опросника ВОЗ ASRS v1.1 и 4 вопроса о том, как человек откладывает дела. Результат сразу, без почты. Это скрининг, а не диагноз.
- [Как устроен тест](${siteUrl('/sdvg-test/metod')}): источник опросника, официальный подсчёт Harvard 0–24, ограничения, где пройти очную диагностику.

## Что мешает начать

- [Все причины](${siteUrl('/pomogaet')}): что мешает начать и что с этим делает Напарник.
${pains}

## Прочее

- [Полный текст публичных страниц одним файлом](${siteUrl('/llms-full.txt')}): тест, вопросы ВОЗ, подсчёт, частые вопросы, каталог «Что мешает начать».
- [Политика конфиденциальности](${siteUrl('/privacy')})
- [Условия использования](${siteUrl('/terms')})
`
  return new Response(body, { headers: { 'Content-Type': 'text/markdown; charset=utf-8' } })
}

export const dynamic = 'force-static'
