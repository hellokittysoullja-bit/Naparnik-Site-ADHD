/**
 * Карточка знания кота — один приём из базы knowledge/ (techniques.md, library/), утверждённый владельцем.
 * Аналог «навыка» Hermes (prompt_builder.py:1300-1360: короткий индекс + загрузка по требованию), но под разовый
 * ход: в промпт попадают только 1–2 карточки, подходящие к реплике человека, а не весь каталог.
 */
export type KnowledgeCard = {
  /** ID приёма из knowledge/techniques.md — связь с доказательствами и решениями владельца */
  readonly id: string
  /** короткое имя для журнала и снимка поверхности */
  readonly title: string
  /** слова и корни, по которым карточка подходит к ситуации (по нормализованному тексту) */
  readonly cues: readonly string[]
  /** что кот знает: 1–3 предложения, как применить приём, — наш текст, доверенный */
  readonly text: string
  /** сила доказательств из базы (●●● / ●● / ●) — при равном совпадении выигрывает более доказанное */
  readonly strength: 1 | 2 | 3
}
