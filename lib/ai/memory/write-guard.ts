import { checkInput } from '../guards/input'
import { despaced, forMatching, matchVariants, stripInvisible } from '../guards/normalize'
import { checkOutput } from '../guards/output'

/**
 * Что можно записать в память о человеке — проверка СОДЕРЖАНИЯ факта до записи (research/20-ai-harness/
 * memory-personalization.md §7.1). Одна функция для всех путей записи: инструмент кота в разговоре, фоновая выжимка
 * после разговора, будущее серверное хранилище. Её зовут и сервер (схема инструмента, выжимка), и устройство перед
 * записью — последний исполнитель проверяет сам (security-ai.md R5).
 *
 * Почему так строго: факт уходит в КАЖДЫЙ следующий разговор. Отравленная запись живёт между сессиями (Hermes
 * tools/memory_tool_store.py:29-32 — скан каждой записи), а лишний факт о человеке с СДВГ хуже пропущенного
 * (стыд, приватность, 152-ФЗ). Источники списков: Claude memory (по умолчанию не хранит здоровье, религию,
 * политику, идентичность; никогда — документы и счета), Hermes background_review.py:383-388 (не выводить черты,
 * настроение, уровень).
 */
export type WriteRejection = 'injection' | 'health' | 'crisis' | 'identity' | 'documents' | 'money' | 'contact' | 'trait' | 'unsafe'

const L = String.raw`\p{L}`
const w = (body: string) => new RegExp(String.raw`(?<!${L})(?:${body})`, 'iu')

/**
 * Указание коту — для подписей стартов и плана при чтении (render.ts): там любой намёк на команду скрывается целиком.
 * Широкое правило: в подписи дела «отвечай», «инструкция», «промпт» не нужны.
 */
export const INSTRUCTION_LIKE =
  /(?<!\p{L})(?:отныне|с этого момента|игнорир\p{L}*|забудь|ты должен|ты обязан|(?:кот|напарник)\p{L}*\s+(?:должен|обязан|всегда|никогда)|отвечай|отвечал\p{L}*|говори|называй\p{L}*|называл\p{L}*\s+себя|вызывай|рекоменд\p{L}*|советуй|советовал\p{L}*|не упоминай|system|assistant|json|prompt|промпт\p{L}*|инструкци\p{L}*)(?!\p{L})/iu

/**
 * Указание коту под видом ФАКТА — уже: факт о человеке законно говорит «научрук рекомендовал», «пишет инструкцию к
 * станку», «игнорирует будильники», «отвечала за отчёты» (аудит 12.11: всё это отклонялось). Ловим повелительное
 * обращение к коту и правила «в каждом ответе».
 */
const FACT_INSTRUCTION =
  /(?<!\p{L})(?:отныне|с этого момента|игнорируй(?:те)?|забудь|ты должен|ты обязан|(?:кот|напарник)\p{L}*\s+(?:должен|обязан|всегда|никогда)|отвечай|говори(?!\p{L})|называй(?:те)?\s+себя|вызывай|советуй|не упоминай|(?:в\s+)?(?:каждом|любом|всех)\s+(?:своём\s+|твоём\s+)?ответ\p{L}*|system|assistant|prompt|ignore|instruction|previous|промпт)(?!\p{L})/iu

// Кризис о третьем лице («не хочет жить») проверка входа не ловит — она про первое лицо; в память не идёт никогда
const CRISIS_FACT = w(
  String.raw`не\s+хоч${L}*\s+(?:жить|просыпаться)|умер(?:еть|ть)|суицид|самоубий|поконч${L}*\s+с\s+собой|сдохн|навредить\s+себе|самоповрежд|порез${L}*\s+себя|реж${L}*\s+себя|исчезн${L}*\s+навсегда|хоч${L}*\s+исчезн|лучше\s+без\s+(?:него|неё|нее|меня)`,
)

// Здоровье: диагнозы, лекарства, врачи, тест — красная линия product-science.md:129 (решение владельца по умолчанию:
// не хранить, memory-personalization.md ⚑1). Слова с бытовым смыслом — только в медицинском окружении: «рецепт
// пирога», «Великая депрессия», «болеет за Спартак», «ходит на концерты», «тест по английскому» — не здоровье
const HEALTH = w(
  [
    String.raw`сдвг|адхд|adhd|синдром\s+дефицит|дефицит${L}*\s+внимани|гиперактив|диагноз|диагностир`,
    String.raw`психиатр|психотерапевт|психолог|невролог|терапевт|врач|доктор|больниц|стационар|лечи(?:тся|лся|лась|ть|т)(?!${L})|лечени`,
    String.raw`антидепресс|таблет|лекарств(?!енн)|медикамент|препарат|доз[аыу](?!${L})|мг(?!${L})|миллиграм|рецепт${L}*\s+(?:врач|на\s+препарат|на\s+лекарств)`,
    String.raw`риталин|метилфенидат|атомоксетин|страттер|элванс|феназепам|элзепам|транквилиз|успокоительн|снотворн|ritalin|concerta|strattera|elvanse|vyvanse|adderall|принима${L}*\s+концерт|концерт${L}*\s+\d+\s*мг`,
    String.raw`(?<!велик${L}*\s)депресси|депрессивн|бипол|тревожн${L}*\s+расстройств|расстройств|птср|шизофр|окр(?!${L})(?!\s+отдел)|аутиз|аутист|диабет|бессонниц|паническ${L}*\s+атак`,
    String.raw`беремен|болезн|боле(?:ет|ю|л|ла)(?!\s+за)(?!${L})|болен|больна|инвалид|asrs|результат${L}*\s+теста(?!\s+по\s)|прош(?:[её]л|ла)\s+тест(?!\s+по\s)|\d+\s*балл${L}*\s+из`,
  ].join('|'),
)
// «С.Д.В.Г.», «с-д-в-г» — слитное прочтение
const HEALTH_GLUED = /сдвг|адхд/u
// Документы, счета, пароли — никогда, даже по просьбе (Claude memory)
const DOCUMENTS = w(String.raw`паспорт(?!${L}*\s+(?:стол|офис))|снилс|инн(?!${L})|полис|пароль|парол${L}*|password|пин(?:-?код)?(?!${L})|cvv|номер\s+карт|карт[аы]\s+\d|сч[её]т\s*№|логин|код\s+(?:от|домофон)|вайфа`)
// длинная цифровая последовательность (номер карты, документа, счёта) — от 8 цифр; даты и «2025–2026» — не номер
const DIGIT_RUN = /\d[\d\s-]*\d/g
const DATES = /\d{4}-\d{2}-\d{2}|\d{1,2}\.\d{1,2}(?:\.\d{2,4})?|(?:19|20)\d{2}\s*[-–—]\s*(?:19|20)\d{2}/g
// цифры словами подряд: «четыре семь один девять»
const DIGIT_WORDS = /(?:(?:ноль|один|одна|два|две|три|четыре|пять|шесть|семь|восемь|девять)[\s,-]+){3,}(?:ноль|один|одна|два|две|три|четыре|пять|шесть|семь|восемь|девять)/iu
function longNumber(text: string): boolean {
  return [...text.replace(DATES, ' ').matchAll(DIGIT_RUN)].some((m) => (m[0].match(/\d/g) ?? []).length >= 8)
}
// Вера, политика, национальность, ориентация, гендерная идентичность — по умолчанию нет. Не ловим учёбу и работу:
// «политех», «политология», «экономическая политика», «Национальный университет»
const IDENTITY = w(
  String.raw`религи|верующ|православ|мусульм|католи|иуде|буддис|атеис|молит|церк|мечет|храм|намаз|рамадан|держ${L}*\s+пост(?!${L})|политическ${L}*\s+взгляд|голосова|партии(?!${L})|партия(?!\s+в\s)|митинг|оппозиц|навальн|либерал|коммунист|национальност|по\s+национальности|татар|башкир|чечен|еврей|армян|грузин|узбек|таджик|ориентаци|гей(?!${L})|лесби|бисексу|асексу|квир|гомосекс|трансгендер|небинарн`,
)
// Деньги в цифрах и долги — не храним (memory-personalization.md §4.4). Учебные «долги по сессии», «займусь», «займёт»,
// «кредиты по ECTS» — не деньги
// числа словами: «восемьдесят тысяч» (набор задач 12.11: «платёж банку восемьдесят тысяч» прошёл фильтр цифр)
const NUM_WORD = String.raw`(?:один|одна|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|\p{L}*надцать|двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|восемьдесят|девяносто|сто|двести|триста|четыреста|пятьсот|шестьсот|семьсот|восемьсот|девятьсот|полтора|пол|несколько|пару)`
const MONEY = w(
  String.raw`${NUM_WORD}\s+(?:тысяч|миллион|миллиард|косар|штук\s+баксов)${L}*(?!\s+(?:слов|знак|шаг|символ|страниц|строк|минут|человек|подписчик))|плат[её]ж${L}*\s+(?:банк|по\s+банк|в\s+банк|по\s+кредит|по\s+ипотек|за\s+квартир)|\d[\d\s]*(?:₽|руб${L}*|р\.|\$|€|долл${L}*|евро|тыс${L}*\.?\s*(?:₽|руб)|к(?!${L}))|долг(?:а|у|ом|и|ов|ам|ами|ах)?(?!${L})(?!\s+по\s+(?:сесси|уч[её]б|предмет|курс|матан|работ|диплом))|задолж|долж(?:ен|на)\s+(?:банк|\d|двест|сто|тысяч|миллион)|кредит(?!${L}*\s+(?:по|ects))|ипотек|заём|займа|займы|займов|микрозайм|зарплат|оклад`,
)
const CONTACT = new RegExp(
  String.raw`[\p{L}\d.+-]+@[\p{L}\d-]+\.[\p{L}\d.]+|(?<!${L})(?:адрес(?!ат)|кв\.|квартир${L}*\s+\d|(?:улиц${L}*|ул\.|проспект${L}*|пр-т)\s+${L}+\s*,?\s*\d|жив${L}*\s+(?:на|в)\s+${L}+(?:\s*,\s*${L}+)?\s+\d{1,3}(?!\d))`,
  'iu',
)
// Догадки о характере и состоянии — не факт, а ярлык (Hermes: «не выводи черты, уровень, настроение»)
const TRAIT = w(
  String.raw`ленив|лентяй|безответствен|неорганизован|несобран|безвол|слабохаракт|прокрастинатор|тупит|туп(?:ой|ая)|тревожн${L}*\s+(?:человек|по\s+натуре)|по\s+натуре|по\s+характеру|склонен|склонна|интроверт|экстраверт|глуп|умн(?:ый|ая)|слаб(?:ый|ая)\s+воля|выгорел|выгоран|в\s+депресс`,
)

/**
 * null — можно записать; иначе причина отказа. Проверка по всем прочтениям текста (латинские двойники, невидимые
 * символы), как у проверки входа: «тaблетки» с латинской «a» не проходят. Латинские слова в факте допустимы
 * («работает в Jira», «помогает Forest»): это не речь кота, а названия из жизни человека (аудит 12.11: правило
 * языка выбрасывало такие факты всегда).
 */
export function factRejection(text: string): WriteRejection | null {
  if (stripInvisible(text) !== text) return 'unsafe'
  const vs = matchVariants(text)
  const any = (r: RegExp) => vs.some((v) => r.test(v))
  if (any(FACT_INSTRUCTION)) return 'injection'
  if (checkInput([text]).crisis || any(CRISIS_FACT)) return 'crisis'
  if (any(HEALTH) || HEALTH_GLUED.test(despaced(text))) return 'health'
  if (any(DOCUMENTS) || longNumber(text) || any(DIGIT_WORDS)) return 'documents'
  if (any(IDENTITY)) return 'identity'
  if (any(MONEY)) return 'money'
  if (any(CONTACT)) return 'contact'
  if (any(TRAIT)) return 'trait'
  // остальное — общие правила вывода кота: ссылки, телефоны, стыд, чужая личность (язык — не причина, см. выше)
  const verdict = checkOutput(text, { maxChars: 400 })
  return verdict.ok || verdict.reason === 'language' ? null : 'unsafe'
}

/**
 * Основание факта — слова человека, а не кота (Hermes background_review: «сохраняй только то, что обосновано
 * репликой»; mem0: «не выдумывать признаки»). Цитата должна найтись в репликах человека: целиком или так, что
 * совпадает не меньше двух третей её слов (модель вправе убрать «ну» и поменять падеж — окончания не сравниваем).
 */
export function groundedIn(evidence: string | undefined, userTexts: readonly string[]): boolean {
  if (!evidence) return false
  const norm = (s: string) => forMatching(s).replace(/[^\p{L}\p{N}]+/gu, ' ').trim()
  const ev = norm(evidence)
  if (ev.length < 3) return false
  const hay = norm(userTexts.join(' \n '))
  if (hay.includes(ev)) return true
  const stem = (x: string) => x.slice(0, 5)
  const words = ev.split(' ').filter((x) => x.length >= 3)
  if (words.length === 0) return false
  const have = new Set(hay.split(' ').map(stem))
  return words.filter((x) => have.has(stem(x))).length / words.length >= 2 / 3
}

const STOP = new Set('котор нужн може очен когд чтоб этот сейч всег обыч челов польз ему него него себя свой своё свою своих тоже ещё уже было будет есть '.split(' '))

/**
 * Факт связан со словами человека, а не только цитата (аудит 12.11: «Работает юристом в Сбере» проходило с цитатой
 * «диплом горит»): не меньше 40 % содержательных основ факта (первые 4 буквы слов от 4 букв, кроме служебных)
 * встречаются в репликах человека. Даты и числа не считаются — «14.11.2026» модель выводит из «в пятницу».
 */
export function factGrounded(text: string, evidence: string | undefined, userTexts: readonly string[]): boolean {
  if (!groundedIn(evidence, userTexts)) return false
  const norm = (s: string) => forMatching(s).replace(/[^\p{L}]+/gu, ' ').trim()
  const stem = (x: string) => x.slice(0, 4)
  const words = norm(text)
    .split(' ')
    .filter((x) => x.length >= 4 && !STOP.has(stem(x)))
  if (words.length === 0) return false
  const have = new Set(norm(userTexts.join(' ')).split(' ').map(stem))
  return words.filter((x) => have.has(stem(x))).length / words.length >= 0.4
}

/**
 * Одно решение «можно ли записать этот факт» для всех путей (инструмент в разговоре, фоновая выжимка):
 *  - сам факт и его цитата проходят запреты (цитата — слова человека: «у меня сдвг, пью риталин, диплом» не может
 *    стать основанием даже безобидного факта — аудит 12.11);
 *  - в репликах, на которые опирается запись, нет кризиса (кризис в память не попадает никогда, а проверка кризиса
 *    в разговоре смотрит только на две последние реплики);
 *  - факт связан со словами человека (factGrounded).
 */
export function writeAllowed(text: string, evidence: string | undefined, userTexts: readonly string[]): boolean {
  if (factRejection(text) !== null) return false
  // цитата — слова самого человека: «забудь», «отвечай» в ней — обычная речь, а не указание коту (набор задач:
  // «забудь про диплом, я его уже сдал» как основание замены отклонялось); остальные запреты — в силе
  const evRejected = evidence !== undefined ? factRejection(evidence) : null
  if (evRejected !== null && evRejected !== 'injection') return false
  if (checkInput([...userTexts]).crisis) return false
  return factGrounded(text, evidence, userTexts)
}

/**
 * Навык (memory/skills.ts) — те же запреты по каждому полю: навык попадает в промпт так же, как факт. Основание —
 * слова человека: цитата из его реплик и связь навыка с ними (не меньше четверти основ — навык описывает действия
 * кота, их слов у человека нет, поэтому порог ниже, чем у факта).
 */
export function skillAllowed(
  skill: { name?: string; when?: string; steps?: string; avoid?: string },
  evidence: string | undefined,
  userTexts: readonly string[],
): boolean {
  const fields = [skill.name, skill.when, skill.steps, skill.avoid].filter((x): x is string => !!x && x.trim() !== '')
  if (fields.some((f) => factRejection(f) !== null)) return false
  if (evidence === undefined || factRejection(evidence) !== null || checkInput([...userTexts]).crisis) return false
  if (!groundedIn(evidence, userTexts)) return false
  const norm = (s: string) => forMatching(s).replace(/[^\p{L}]+/gu, ' ').trim()
  const stem = (x: string) => x.slice(0, 4)
  const words = norm(fields.join(' ')).split(' ').filter((x) => x.length >= 4 && !STOP.has(stem(x)))
  if (words.length === 0) return false
  const have = new Set(norm(userTexts.join(' ')).split(' ').map(stem))
  return words.filter((x) => have.has(stem(x))).length / words.length >= 0.25
}
