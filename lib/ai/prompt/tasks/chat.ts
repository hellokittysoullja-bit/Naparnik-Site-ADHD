function timeOfDay(hour: number): string {
  if (hour >= 5 && hour < 12) return 'утро'
  if (hour >= 12 && hour < 18) return 'день'
  if (hour >= 18 && hour < 23) return 'вечер'
  return 'ночь'
}

/** Время суток у человека; без часа (бот не знает часового пояса) — блока нет, а не выдуманный полдень */
export function situation(hour: number | undefined): string | undefined {
  if (typeof hour !== 'number') return undefined
  return dataBlock('situation', { 'время суток': timeOfDay(hour), час: hour })
}
