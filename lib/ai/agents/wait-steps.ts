/** Ожидание в плане дела: без базы и без модели — годится и сайту, и боту (22.11, research/30-estimate) */

/**
 * Шаг-ожидание: ничего делать не надо, только ждать (сохнет, решение налоговой, доставка). Короткое ожидание рядом
 * (стирка, духовка, доставка еды — до двух часов) входит в твоё время, как у goblin.tools; долгое (ночь, дни, недели)
 * показывается отдельно: «работы 2 часа» и «ждать 30 дней» — разные вещи (22.11, сравнение с Estimator).
 */
const WAIT =
  /^(?:дождаться|ожидать|подождать|ждать|дать\s+(?:\S+\s+){0,2}(?:полностью\s+)?(?:высохнуть|просохнуть|остыть|отстояться|настояться|застыть|затвердеть|постоять|подсохнуть|впитаться)|оставить\s.*(?:высых|сохнуть|на ночь|на сутки|настаива|остыва|застыва|отстаива|пропит)|(?:высушить|просушить)\s.*(?:на воздухе|естественн|в тёплом|в теплом|сухом месте))/i
/** ожидание без слова «ждать»: «Получить результаты анализов» (сутки) — ответ, решение, результаты, готовность */
export const RESULT = /^(?:получить|узнать)\s+(?:результат|ответ|решени|одобрени|подтверждени|готов)/i
/** работа и ожидание в одном шаге: «Нанести слой краски и дать высохнуть» — руки только на нанесение */
const TAIL_WAIT = /(?:и|,)\s+(?:дать|оставить)\s+(?:\S+\s+){0,2}(?:полностью\s+)?(?:высохнуть|просохнуть|высыхать|сохнуть|остыть|застыть|затвердеть|настояться|пропитаться)|за несколько часов|на ночь|на сутки/i
/** шаг не для всех: «Если планируется подарок…», «При желании…» — в среднем делает половина */
const OPTIONAL = /^(?:если|при желании|при необходимости|по желанию|в случае)|при необходимости|если нужно|если требуется/i
export const isWaitStep = (text: string) => WAIT.test(text.trim())
export const LONG_WAIT = 120
/** сколько рук в шаге «сделать и дать высохнуть» */
const TAIL_WORK = 60

/** твоё время и долгое ожидание отдельно */
export function splitMinutes(steps: readonly string[], minutes: readonly number[]): { work: number; wait: number } {
  let work = 0
  let wait = 0
  steps.forEach((s, i) => {
    const m = minutes[i] ?? 0
    const t = s.trim()
    if (m > LONG_WAIT && (isWaitStep(t) || RESULT.test(t))) wait += m
    else if (m > LONG_WAIT && TAIL_WAIT.test(t)) {
      work += TAIL_WORK
      wait += m - TAIL_WORK
    } else work += OPTIONAL.test(t) ? m / 2 : m
  })
  return { work: Math.round(work), wait: Math.round(wait) }
}
