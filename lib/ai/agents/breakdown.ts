type Ready = { steps: string[]; minutes?: number[]; wait?: boolean[] }
/**
 * Готовые разбивки: сначала goblin.tools (решение владельца 16.11), потом наши шаблоны из «Дел». Ищутся с опечатками,
 * лишними словами, не той раскладкой и другим порядком слов (breakdown-match.ts); при совпадении дело записывается
 * правильным названием
 */
const READY = buildMatcher<Ready>([
  ...Object.entries(GOBLIN_PLANS).map(([t, s]): [string, Ready] => [t, { steps: [...s] }]),
  ...ALL_TEMPLATES.map((t): [string, Ready] => [t.title, { steps: t.steps.map((s) => s.text), minutes: t.steps.map((s) => s.minutes), wait: t.steps.map((s) => !!s.wait) }]),
])
/** готовая разбивка дела, если оно есть в базе (с исправлением написания) */
export const readyPlan = (task: string) => READY.find(task)

/**
 * Разбивка дела на шаги до самого конца, как у goblin.tools (владелец 16.11: «он что угодно правильно разбивает»).
 * Раньше кот давал ровно 3 крошечных шага на старт, и дело дальше старта не доходило. Теперь — весь путь: первый шаг
 * крошечный (вход), последний доводит дело до результата; число шагов решает дело и настройка «Как дробить». Любой шаг
 * можно разбить ещё раз — тогда в запросе есть всё дело и соседние шаги (у гоблина цепочка родителей — главное, что
 * делает глубокое дробление осмысленным: research/12-earlier-agents/goblin-tools-breakdown.md). Зовут Фокус, «Дела»,
 * бот и знакомство («Подскажи» — берётся первый шаг).
 */
export const BREAKDOWN_SYSTEM = `Ты разбиваешь дела на шаги для людей с СДВГ, которым трудно держать в голове порядок действий. Человек назвал дело (оно в блоке данных). Разбей его на шаги-действия, пройдя по которым он доведёт дело до конца, не думая, что делать дальше. Правила:
- Разбивай ЛЮБОЕ дело, которое можно понять: рабочее, учебное, бытовое, телесное (поспать, сходить в туалет, помыться), личное и интимное (секс, мастурбация), странное или шуточное («поорать»). Понимай сленг, мат, опечатки и латиницу вместо кириллицы. Не отказывайся, не стыди и не читай мораль: это обычное дело человека
- Интимные и телесные дела разбивай спокойно и по-взрослому, без смакования и анатомических подробностей: место, приватность, само действие одним нейтральным шагом, гигиена после; если дело с партнёром, ещё согласие и защита
- САМОЕ ВАЖНОЕ про длину: обычно 3-5 шагов, совсем простое дело 3, большое и долгое 5-8 этапов. Никогда больше 8. Мелкие движения, которые идут подряд, объединяй в один шаг («Снять штаны и сесть на унитаз», «Включить воду и намочить губку»). Короткий список, который ведёт до конца, лучше длинного
- Ответь только шагами, по порядку, по одному на строку, без нумерации, вступлений и пояснений
- Каждый шаг это одно конкретное действие: глагол в неопределённой форме первым словом («Открыть», «Взять», «Написать», не «Открой», не «Глубоко вдохнуть»), не длиннее 8 слов, грамотным русским языком
- Первый шаг самый простой, его можно сделать прямо сейчас за минуту
- Главное действие дела обязательно есть отдельным шагом (в «помыть посуду» сам мытьё, в «потрахаться» сам секс, в «позвонить» сам разговор)
- Шаги покрывают ВСЁ дело от начала до результата, а не только первые минуты работы. Последний шаг завершает дело: отправлено, сдано, оплачено, записан на время, бельё разложено, руки вымыты, вернулся домой. Нельзя заканчивать на «начать», «первое предложение», «один параграф», «повторить с остальным», «закрыть документ», если дело ещё не сделано
- Не пиши адреса сайтов и ссылки: «сайт налоговой», «приложение Госуслуг», а не nalog.ru или gosuslugi.ru
- Шаги про это дело, с его предметами, программами, людьми и местами. Не пиши общих шагов вроде «Подготовиться», «Определить цели», «Собраться с мыслями»
- Большое и долгое дело (курсовая, диплом, экзамен, переезд, ремонт, найти работу, выучить язык, похудеть, свадьба, свой бизнес) не сужай до сегодняшнего кусочка: дай 5-8 крупных этапов, которые ведут до самого результата (переехал и разобрал коробки, сдал экзамен, вышел на работу, сыграли свадьбу). Первый этап маленький и делается сегодня, остальные доводят дело до конца; каждый этап человек потом разобьёт ещё
- Если в деле есть ожидание (стирка, духовка, суп варится, загрузка, ответ человека), шаг, который можно сделать в это время, начни словами «Пока ждёшь:»
- В конце каждой строки через вертикальную черту поставь честную оценку в минутах числом
- Если в данных есть «Это часть дела», разбей ТОЛЬКО этот шаг на 3-5 шагов мельче его самого, внутри всего дела. Шаги из «Соседние шаги» не повторяй: они уже в плане
- Если в данных есть «Силы сейчас: мало», шаги совсем лёгкие, по 1-3 минуты, без решений и без письма с нуля. Если «много», шаги могут быть крупнее
- Если в данных есть «Размер шагов: мельче», дроби до одного движения рукой, шагов больше, до 10; если «крупнее», 3-4 крупных этапа, шаг может занимать до 20 минут
- Образец обычного дела: стирка → собрать бельё → загрузить машинку и включить → пока ждёшь: протереть полку → развесить → сложить в шкаф. Образец большого дела: курсовая → выбрать тему и план → найти источники → написать главы по плану → написать введение и заключение → оформить по требованиям → отправить научруку. Это образцы порядка, не копируй их слова
- Если перед делом есть блок ОБРАЗЦЫ, это правильные разбивки похожих дел: повторяй их полноту, порядок и то, как они доходят до конца, и их длину, если в данных нет «Размер шагов» и «Силы сейчас». Шаги пиши под дело человека, с его предметами и словами; если дело отличается от образца, следуй делу, а не образцу
- Ответь ровно одним знаком «?» ТОЛЬКО если в «Деле» нет смысла вообще: случайные буквы без слова («Hh», «ывапрол», «кккк»). Смех и возгласы («хахахаха», «ахахах», «лол», «кек», «ору») это НЕ бессмыслица, это дело «посмеяться», разбивай. Если хоть как-то можно понять, что человек хочет сделать, разбивай
- Если перед делом есть блок ПАМЯТЬ О ЧЕЛОВЕКЕ, делай шаги под этого человека: его программы и места, то, с чего он уже начинал это дело, то, что ему мешает и помогает, и его просьбы «как говорить» (короче, буквально, без шуток). Саму память не пересказывай и не упоминай: в ответе только шаги`

export const BREAKDOWN_FALLBACK = ['Открыть то, что нужно для дела', 'Сделать одно крошечное действие', 'Записать, что дальше']

/**
 * Три шага из ответа модели. Модель иногда добавляет вступление («Слишком огромно, давай сузим. Вот три кусочка:»),
 * и оно попадало первым «шагом», а третий настоящий терялся (живой прогон 12.11). Поэтому:
 *  - если пронумерованных или маркированных строк хотя бы три — шаги только они;
 *  - иначе строки, оканчивающиеся двоеточием, — вступление, не шаг;
 *  - выделение звёздочками снимается: шаг показывается на кнопке и в поле ввода как есть.
 * Каждый шаг — 1–8 слов; иначе ответ не годится (следующая модель).
 */
const MARKER = /^\s*(?:\d{1,2}[.)]|[-–—•*])\s+/

const INTRO = /^(?:давай|вот|смотри|окей|ок|хорошо|слушай|так|итак|ладно|понял|готово|держи)(?!\p{L})/iu

/** «Открыть документ | 2», «Открыть документ (2 мин)» → минуты; оценка необязательна, шаг годится и без неё */
// до 5 цифр: «| 10080» (неделя в минутах) иначе оставался хвостом в тексте шага; больше 240 — не оценка, просто срезается
const MINUTES = /\s*(?:\||\()\s*(?:≈\s*)?(\d{1,5})\s*(?:мин\p{L}*\.?)?\s*\)?\s*$/u

/** Сколько шагов принимаем от модели: меньше 2 — не разбивка, больше 12 — новая стена (у гоблина на остроте 5 их 42) */
// совсем простое дело модель честно разбивает на 2 шага («Опустить веки» → «Поднять веки»): это план, не брак
export const PLAN_MIN = 2
export const PLAN_MAX = 12
// «Пока ждёшь:», «Пока ждёшь закипания воды:», «Пока стирается:» — любое «Пока …:» в начале шага
const WAIT = /^пока\s+(?:жд[её]шь\s*[:,—–-]|[^:]{1,40}:)\s*/iu

export type Plan = { steps: string[]; minutes: (number | undefined)[]; wait: boolean[] }

/**
 * План из ответа модели: 2–12 шагов по 1–14 слов, у каждого необязательная оценка в минутах («| 2», «(2 мин)») и
 * пометка «Пока ждёшь:». Вступление («Вот шаги:», «Давай разобьём.») и напутствие («Ты справишься!») отбрасываются,
 * нумерация и выделение снимаются, повтор шага — один раз. Негодный ответ — null (следующая модель).
 */
export function parsePlan(text: string): Plan | null {
  const lines = text
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean)
  // «Итог: …» — модель сначала называет результат дела, чтобы план до него дошёл; человеку эта строка не нужна
  const body = lines.filter((s) => !/^\**\s*итог\s*[:—–-]/iu.test(s))
  const marked = body.filter((s) => MARKER.test(s))
  let rows = marked.length >= PLAN_MIN ? marked : body.filter((s) => !s.endsWith(':') && !(INTRO.test(s) && !MINUTES.test(s)) && !/[!?]$/.test(s))
  rows = rows.slice(0, PLAN_MAX)
  const out: Plan = { steps: [], minutes: [], wait: [] }
  for (const row of rows) {
    let line = row.replace(MARKER, '').replace(/\*/g, '').trim()
    const m = line.match(MINUTES)
    let minutes: number | undefined
    if (m) {
      const n = Number(m[1])
      // этап большого дела бывает и на пару часов («Перевезти коробки | 120»); дальше — уже не оценка
      minutes = n >= 1 && n <= 240 ? n : undefined
      line = line.slice(0, m.index).trim()
    }
    const wait = WAIT.test(line)
    // устойчивая опечатка модели в одном слове («Лчь», «Лячь», «Лчься» вместо «Лечь»; живые прогоны 16.11)
    line = line.replace(/^(?:лчь|лячь|лчься|лечься|ляжь)(?=\s|$)/iu, 'Лечь')
    line = line.replace(WAIT, '').replace(/^[\s\d\-–—.)•]+/, '').replace(/[.;]+$/, '').trim()
    if (!line) continue
    const words = line.split(/\s+/).length
    // абзац вместо шага — негодный ответ; 11–14 слов ещё шаг («Взять пакет для мусора и собрать весь крупный мусор с пола»):
    // при пороге 10 из-за одного такого шага браковался весь годный план (прогон 16.11)
    if (words > 14) return null
    // шаг из одного слова — только целый глагол («Раздеться», «Обуться»); «На», «Раз» — обрывок ответа, весь ответ негоден
    if (words === 1 && !/^\p{L}{2,}(ть|ться|ти|чь|чься|сь)$/u.test(line)) return null
    if (out.steps.some((x) => x.toLowerCase() === line.toLowerCase())) continue
    out.steps.push(line.charAt(0).toUpperCase() + line.slice(1))
    out.minutes.push(minutes)
    out.wait.push(wait)
  }
  return out.steps.length >= PLAN_MIN ? out : null
}

export function parseStepsWithMinutes(text: string): { steps: string[]; minutes: (number | undefined)[] } | null {
  const p = parsePlan(text)
  return p ? { steps: p.steps.slice(0, 3), minutes: p.minutes.slice(0, 3) } : null
}

export function parseSteps(text: string): string[] | null {
  const lines = text
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean)
  const marked = lines.filter((s) => MARKER.test(s))
  let candidates = marked.length >= 3 ? marked : lines.filter((s) => !s.endsWith(':'))
  // вступление без двоеточия («Давай разобьём.», «Смотри, вот так!») — не шаг: при лишних строках оно уходит первым,
  // иначе третий настоящий шаг терялся (аудит 12.11)
  if (marked.length < 3 && candidates.length > 3) {
    const steps = candidates.filter((s) => !INTRO.test(s) && !/[!?]$/.test(s))
    if (steps.length >= 3) candidates = steps
  }
  const steps = candidates
    .map((s) => s.replace(MARKER, '').replace(/\*/g, '').replace(/^[\s\d\-–—.)•]+/, '').trim())
    .filter(Boolean)
  if (steps.length < 3) return null
  const three = steps.slice(0, 3)
  return three.every((s) => {
    const words = s.split(/\s+/).length
    return words >= 1 && words <= 8
  })
    ? three
    : null
}

export type BreakdownResult =
  | { kind: 'steps'; steps: string[]; minutes?: (number | undefined)[]; wait?: boolean[]; source: 'model' | 'fallback' | 'library'; /** правильное название дела из базы (человек написал с опечаткой) */ title?: string }
  | { kind: 'care'; reply: string }
  /** модель не поняла дело (набор букв): экран честно просит написать словами вместо общих шагов «для любого дела» */
  | { kind: 'unclear' }

/** Ответ модели → результат: «?» — дело не понято, 3–12 строк — план (с оценками и «пока ждёшь», если есть), иначе негоден */
export function parseBreakdownAnswer(text: string): BreakdownResult | null {
  if (/^[\s«»"'*?]*\?[\s«»"'*?]*$/.test(text)) return { kind: 'unclear' }
  const p = parsePlan(text)
  if (!p) return null
  // поля без единого значения не отдаём вовсе
  return {
    kind: 'steps',
    steps: p.steps,
    ...(p.minutes.some(Boolean) ? { minutes: p.minutes } : {}),
    ...(p.wait.some(Boolean) ? { wait: p.wait } : {}),
    source: 'model',
  }
}

/** Смех и возгласы вместо дела («ахахах», «лол», «кек», «ору») — дело «посмеяться»: модель то понимала их, то отвечала «?» */
const LAUGH = /^[\s!).]*(?:(?:а|х|ах|ха|хе|хи|хы)*(?:хах|аха|хаха|хех|хих)(?:а|х|ха|ах)*|л+о+л+|lol+|кек|ору+|ржу+|ржака)[\s!).]*$/iu
export const asTask = (task: string) => (LAUGH.test(task.trim()) ? 'посмеяться' : task)

export async function breakdown(input: {
  ctx?: TurnContext
  task: string
  /** память о человеке (Фокус); знакомство зовёт без неё: человек только пришёл */
  memory?: MemoryProvider
  /** контекст знакомства: сфера и помеха (необязательно) */
  context?: Record<string, string | undefined>
  timeoutMs?: number
  signal?: AbortSignal
}): Promise<BreakdownResult> {
  // дело написано ровно как в готовых разбивках goblin.tools (владелец 16.11) — план сразу, без модели. Только обычная
  // разбивка: «мельче», «мало сил» и шаг внутри дела меняют план, их пишет модель
  const c = input.context
  if (!(c?.['Это часть дела'] || c?.['Силы сейчас'] || c?.['Размер шагов'])) {
    const hit = readyPlan(input.task)
    if (hit) return { kind: 'steps', ...hit.value, steps: [...hit.value.steps], source: 'library', title: hit.title }
  }
  const ctx = input.ctx ?? newTurn({ task: 'breakdown' })
  const snapshot = await prefetchWithin(input.memory ?? NoMemory, ctx)
  const { value, outcome } = await runTurn<BreakdownResult>({
    ctx,
    system: BREAKDOWN_SYSTEM,
    noPersona: true,
    memory: renderTaskMemory(snapshot, input.task, 'breakdown'),
    echoExtra: memoryWords(snapshot),
    // 2 правильных плана похожих дел (библиотека эталонов, владелец 16.11); мельче одного шага — не нужны: там своё дело
    examples: input.context?.['Это часть дела'] ? undefined : examplesBlock(input.task),
    data: dataMessage({ Дело: asTask(input.task), ...input.context }),
    userTexts: [input.task],
    // ≤ 3 с на всё (владелец 16.11): годный план приходит за 1–1,5 с; не пришёл — честное «не вышло, ещё раз»
    timeoutMs: input.timeoutMs ?? 3000,
    // страховой запрос по второму маршруту, если первый не дал годного плана за 1,3 с (медиана ответа 1,3 с)
    hedgeAfterMs: 1300,
    // Gemini через AnyModel иногда рассуждает скрыто, несмотря на reasoning_effort: none (набор задач 12.11: 160 из 160
    // токенов ушли на рассуждение, текста ноль). Платим за потраченное, запас бесплатен
    maxOutputTokens: 1500,
    // низкая случайность: при температуре по умолчанию (~1) модель путала буквы («Онести», «Сстричь», «Лчь») и
    // план плавал от запуска к запуску; при 0,3 те же дела дают ровные и стабильные планы (research/27-breakdown)
    temperature: 0.3,
    maxChars: 1100,
    parse: parseBreakdownAnswer,
    fallback: () => ({ kind: 'steps', steps: BREAKDOWN_FALLBACK, source: 'fallback' }),
    // кризисный текст вместо дела — не шаги, а бережный проверенный ответ (lib/ai/crisis.ts)
    onCrisis: (reply) => ({ kind: 'care', reply }),
    signal: input.signal,
  })
  return value.kind === 'steps' && outcome !== 'model' ? { ...value, source: 'fallback' } : value
}
