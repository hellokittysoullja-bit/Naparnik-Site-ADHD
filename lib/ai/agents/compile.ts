import { readyTitle } from './breakdown'
import { VERB_FORMS, VERB_FORMS_LEAD } from './breakdown-verb-forms'

/**
 * Компилятор (владелец 22.11: «как Compiler у goblin.tools, только без модели»): поток мыслей → список дел.
 * «блин надо отчёт доделать, ещё к врачу записаться, а, и маме позвонить, посуда со вчера стоит» →
 * «Доделать отчёт», «Записаться к врачу», «Позвонить маме», «Помыть посуду».
 *
 * Без модели, по правилам (research/31-compiler/README.md):
 *  1) режем на фразы: знаки препинания, переносы, связки «ещё», «потом», «а также», «а», «и» перед новым делом;
 *  2) счищаем разговорное: «блин», «надо», «не забыть», «наконец», «сегодня», «хоть когда-нибудь», «а то …», «если …»;
 *  3) фраза с глаголом в неопределённой форме — дело: глагол вперёд («отчёт доделать» → «доделать отчёт»), форма
 *     «помою» → «помыть»; то, что стоит перед глаголом вместе с чужим глаголом («мама просила помочь»), отбрасываем;
 *  4) «не сделал» → сделать: «подарок не купил» → «Купить подарок», «диплом не пишу» → «Писать диплом»;
 *  5) жалобы → действие: «наполнитель кончился» → «Купить наполнитель», «штраф пришёл» → «Оплатить штраф»;
 *  6) фраза без глагола — спрашиваем базу дел: «посуда со вчера стоит» → «Помыть посуду», «зал» → «Сходить в
 *     спортзал»; «к стоматологу», «в деканат» → «Сходить к стоматологу»;
 *  7) голое дополнение берёт глагол соседа: «разобрать шкаф, и балкон тоже» → «Разобрать балкон»;
 *  8) чувства, рассказ о других и общие слова («мне плохо», «он ждёт неделю», «всё горит») — не дела.
 */

const MAX = 20

/** знаки и связки, на которых кончается одно дело и начинается другое */
const HARD =
  /[.!?;\n]+|,|:|\s[—–-]\s|\s+(?:и\s+)?(?:ещё|еще|потом|затем|а также|а ещё|а еще|плюс|и также)\s+|\s+а\s+(?=я\s|мне\s|у меня\s|ещё\s|еще\s|то\s)/i

/** разговорное в начале фразы — снимаем, пока снимается */
const LEAD =
  /^(?:а|и|но|ну|ой|блин|блять|бля|короче|в общем|вообще|так|ладно|типа|вот|кстати|также|тоже|ещё|еще|потом|сначала|наконец|наконец-то|хотя бы|хоть|наверное|наверно|может|может быть|кажется|сегодня|завтра|послезавтра|вечером|утром|днём|днем|ночью|в выходные|на выходных|на неделе|в понедельник|во вторник|в среду|в четверг|в пятницу|в субботу|в воскресенье|надо бы|надо|нужно|нужно бы|мне надо|мне нужно|мне бы|нам надо|я должен|я должна|должен|должна|хочу|хотелось бы|хочется|планирую|собираюсь|пора|не забыть|не забудь|обязательно|срочно|я|опять|снова|уже|до конца недели|до пятницы|к пятнице|сегодня же|ну и)\s+/i

/** хвосты: время, причины, оговорки */
const TAIL =
  /\s+(?:хоть когда-нибудь|когда-нибудь|наконец|наконец-то|тоже|уже|не забыть|обязательно|срочно|наверное|может быть|пожалуйста|сначала)$|\s+(?:а то|если|потому что|так как|чтобы не|иначе|пока не|из-за того)\s.*$|\s+уже\s+\S+(?:\s+\S+)?$/i

/** слова-пустышки внутри фразы: «работу надо искать», «курсы какие пройти», «этот дурацкий шкаф» */
const INNER = /\s+(?:надо|нужно|бы|какие|какие-нибудь|какие-то|какой-нибудь|хоть|наверное|уже|этот|эту|эти|этого|дурацкий|дурацкую|дурацкие|чёртов|чертов|чёртову|чертову)(?=\s|$)/gi

/** фраза-причина или оговорка целиком: «а то места нет», «если не заплачу» */
const REASON = /^(?:а то|то|иначе|потому что|так как|если|когда|пока)\b/i

/** чувства и общие слова — не дела */
const NOT_A_TASK =
  /^(?:мне\s+)?(?:плохо|грустно|тяжело|лень|страшно|тревожно|ничего не (?:хочу|успеваю|понимаю|хочется)|всё горит|все горит|у меня куча всего|куча всего|всё навалилось|все навалилось|работа|учёба|учеба|дом|семья|жизнь|всё|все|ничего|ну|а|и|вот|так|ладно|в общем|вообще|короче|сегодня|завтра|послезавтра|в выходные|на выходных|в понедельник|во вторник|в среду|в четверг|в пятницу|в субботу|в воскресенье|вечером|утром|днём|днем|что-то делать.*|что делать.*|не понимаю.*|вообще не понимаю.*)$/i

/**
 * Глагол в личной форме или прошедшем времени: «стоит», «ждёт», «пишет», «просила», «греется» — рассказ, не дело.
 * По окончанию не угадываем («отчёт», «деканат», «билет» — не глаголы): только формы из словаря базы и явные окончания
 */
const FINITE_END = /(?:ется|ится|ются|ятся|утся|атся|ешься|ишься|ала|ила|ела|яла|али|или|ели|яли)$/i
const FINITE_WORDS = new Set(['молчу', 'хочу', 'могу', 'болит', 'болят', 'отключат', 'отключили', 'стоит', 'стоят', 'висит', 'висят', 'лежит', 'ждёт', 'ждет', 'ждут', 'пишет', 'пишут', 'просил', 'просила', 'сказал', 'сказала', 'воняет', 'горит', 'блевал', 'блевала', 'тошнит', 'греется', 'знаю', 'успеваю', 'понимаю'])
const isFinite = (w: string) => {
  const x = low(w)
  if (FINITE_WORDS.has(x) || FINITE_END.test(x)) return true
  const v = VERB_FORMS[x]
  return v !== undefined && v !== x && !/(?:ю|у)$/.test(x)
}
const PRONOUN = /^(?:он|она|оно|они|то|это|кто-то|все|всё|научник|начальник)$/i

/** «X кончился» → «Купить X»: простые жалобы, у которых одно понятное действие */
const COMPLAINTS: [RegExp, string][] = [
  [/^(.+?)\s+(?:кончил(?:ся|ась|ось|ись)|закончил(?:ся|ась|ось|ись)|заканчива(?:ется|ются)|на исходе)$/i, 'Купить'],
  [/^(?:кончил(?:ся|ась|ось|ись)|закончил(?:ся|ась|ось|ись)|нет)\s+(.+)$/i, 'Купить'],
  [/^(.+?)\s+(?:сломал(?:ся|ась|ось|ись)|не работа(?:ет|ют)|барахлит|глючит)$/i, 'Починить'],
  [/^(?:пришёл|пришел|пришла|пришло|пришли)\s+(.+)$/i, 'Оплатить'],
  [/^(.+?)\s+(?:пришёл|пришел|пришла|пришло|пришли|не оплачен(?:а|о|ы)?|отключат|отключили)$/i, 'Оплатить'],
]

const tidy = (s: string) => s.replace(/[«»"“”()]/g, ' ').replace(/\s+/g, ' ').trim()
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)
const low = (s: string) => s.toLowerCase().replace(/ё/g, 'е')

function strip(s: string): string {
  let t = tidy(s)
  for (let i = 0; i < 8; i++) {
    const next = t.replace(LEAD, '').replace(TAIL, '').trim()
    if (next === t) break
    t = next
  }
  return t.replace(INNER, '').replace(/^[,\s-]+|[,\s-]+$/g, '').trim()
}

/** винительный падеж одного слова для «Купить/Оплатить …»: «квартплата» → «квартплату» */
function accusative(obj: string): string {
  const ws = obj.split(' ')
  if (ws.length === 1 && /[^аеиоуыэюя]а$/i.test(ws[0])) return ws[0].replace(/а$/i, 'у')
  if (ws.length === 1 && /я$/i.test(ws[0]) && !/ия$/i.test(ws[0])) return ws[0].replace(/я$/i, 'ю')
  return obj
}

/** слово — глагол в неопределённой форме или в будущем/настоящем первого лица («помою», «позвоню») */
function verbOf(w: string, lead: boolean): string | null {
  const x = low(w)
  if (/(?:ть|ться|чь|чься|ти|тись)$/.test(x) && x.length > 3 && !/^(?:сеть|мать|тетрадь|кровать|площадь|путь|часть|ветеринар)$/.test(x)) return x
  // формы прошедшего времени и третьего лица — рассказ («просила», «пишет»), их здесь не берём
  if (isFinite(x)) return null
  return VERB_FORMS[x] ?? (lead ? (VERB_FORMS_LEAD[x] ?? null) : null)
}

/** глагол вперёд, форма → неопределённая: «отчёт доделать» → «доделать отчёт», «помою посуду» → «помыть посуду» */
function asAction(s: string): string | null {
  const ws = s.split(' ')
  const i = ws.findIndex((w, k) => verbOf(w, k === 0) !== null)
  if (i < 0) return null
  const v = verbOf(ws[i], i === 0) as string
  if (ws[i - 1] && low(ws[i - 1]) === 'не') return null
  let before = ws.slice(0, i)
  // «мама просила помочь …», «он ждёт ответа» — перед глаголом чужое действие: берём только от глагола
  if (before.some((w) => isFinite(w) || PRONOUN.test(w))) before = []
  return [v, ...before, ...ws.slice(i + 1)].filter(Boolean).join(' ')
}

/** «подарок не купил», «диплом не пишу» → «купить подарок», «писать диплом» */
function undone(s: string): string | null {
  const m = s.match(/^(.+?)\s+не\s+(\S+)$/i) ?? s.match(/^не\s+(\S+)\s+(.+)$/i)
  if (!m) return null
  const [obj, verb] = s.match(/^не\s/i) ? [m[2], m[1]] : [m[1], m[2]]
  const v = VERB_FORMS[low(verb)] ?? VERB_FORMS_LEAD[low(verb)]
  if (!v || /^(?:ничего|всё|все|ничем|никак|никуда|ни\s)/i.test(obj) || obj.split(' ').length > 3 || obj.split(' ').some((w) => isFinite(w) || PRONOUN.test(w))) return null
  return `${v} ${obj}`
}

/** «и» перед новым делом: «… маме позвонить и кота покормить» режем, «молоко и хлеб» — нет */
function splitAnd(s: string): string[] {
  const parts = s.split(/\s+и\s+/i)
  if (parts.length < 2) return [s]
  const out: string[] = [parts[0]]
  for (const p of parts.slice(1)) {
    if (asAction(strip(p)) !== null || undone(strip(p)) !== null) out.push(p)
    else out[out.length - 1] = `${out[out.length - 1]} и ${p}`
  }
  return out
}

/** база дел узнаёт фразу без глагола: «посуда со вчера стоит» → «Помыть посуду», «зал» → «Сходить в спортзал» */
function fromBase(s: string): string | null {
  const bare = s.replace(/\s+(?:стоит|стоят|висит|висят|лежит|лежат|ждёт|ждет|валяется|копится|со вчера|с утра|с прошлой недели|\d+\s*(?:час|часа|часов|минут|мин))(?:\s.*)?$/i, '')
  for (const t of [s, bare]) {
    if (!t || t.length < 3) continue
    const title = readyTitle(t)
    if (title && asAction(title)) return title
  }
  // «к стоматологу», «в деканат за справкой», «на техосмотр» — куда-то сходить
  if (/^(?:к|ко|в|во|на)\s+\S+/i.test(s) && s.split(' ').length <= 5) return `сходить ${s}`
  return null
}

/** дополнение без своего смысла: одно-три слова, без глагола и местоимений, без чисел */
const bareObject = (s: string) => {
  const ws = s.split(' ')
  return ws.length <= 3 && !/\d/.test(s) && !ws.some((w) => isFinite(w) || PRONOUN.test(w) || low(w) === 'не')
}

/**
 * Местоимение — тот, о ком шла речь (как у goblin.tools): «записать ребёнка в бассейн, купить ему кроссовки» →
 * «Купить ребёнку кроссовки», «продать старый велик, сфоткать его» → «Сфоткать старый велик». Люди — по словарю
 * падежей; вещь — дополнение прошлого дела (мужской род неодушевлённого: винительный = именительный)
 */
type Person = { g: 'm' | 'f'; acc: string; dat: string }
const P = (g: 'm' | 'f', acc: string, dat: string, ...forms: string[]): [string[], Person] => [forms, { g, acc, dat }]
const PEOPLE: [string[], Person][] = [
  P('m', 'ребёнка', 'ребёнку', 'ребёнок', 'ребёнка', 'ребенка', 'ребёнку', 'ребенку', 'ребёнком', 'ребенок'),
  P('m', 'сына', 'сыну', 'сын', 'сына', 'сыну', 'сыном'),
  P('f', 'дочку', 'дочке', 'дочь', 'дочку', 'дочке', 'дочери', 'дочкой'),
  P('f', 'бабушку', 'бабушке', 'бабушка', 'бабушку', 'бабушке', 'бабушкой', 'бабушки', 'бабуле', 'бабулю'),
  P('m', 'дедушку', 'дедушке', 'дедушка', 'дедушку', 'дедушке', 'дедушкой', 'дедушки'),
  P('f', 'маму', 'маме', 'мама', 'маму', 'маме', 'мамой', 'мамы'),
  P('m', 'папу', 'папе', 'папа', 'папу', 'папе', 'папой', 'папы'),
  P('m', 'брата', 'брату', 'брат', 'брата', 'брату', 'братом'),
  P('f', 'сестру', 'сестре', 'сестра', 'сестру', 'сестре', 'сестрой', 'сестры'),
  P('m', 'мужа', 'мужу', 'муж', 'мужа', 'мужу', 'мужем'),
  P('f', 'жену', 'жене', 'жена', 'жену', 'жене', 'женой'),
  P('m', 'парня', 'парню', 'парень', 'парня', 'парню', 'парнем'),
  P('f', 'подругу', 'подруге', 'подруга', 'подругу', 'подруге', 'подругой'),
  P('m', 'друга', 'другу', 'друг', 'друга', 'другу', 'другом'),
  P('m', 'кота', 'коту', 'кот', 'кота', 'коту', 'котом'),
  P('f', 'кошку', 'кошке', 'кошка', 'кошку', 'кошке', 'кошкой'),
  P('f', 'собаку', 'собаке', 'собака', 'собаку', 'собаке', 'собакой'),
  P('m', 'пса', 'псу', 'пёс', 'пса', 'псу'),
  P('m', 'начальника', 'начальнику', 'начальник', 'начальника', 'начальнику'),
]
const personIn = (t: string): Person | null => {
  for (const w of low(t).split(' ')) for (const [forms, p] of PEOPLE) if (forms.some((f) => low(f) === w)) return p
  return null
}
function resolve(item: string, person: Person | null, thing: string | null): string {
  return item
    .split(' ')
    .map((w, i) => {
      if (i === 0) return w
      const x = low(w)
      if (person && x === 'ему' && person.g === 'm') return person.dat
      if (person && x === 'ей' && person.g === 'f') return person.dat
      if (person && x === 'его' && person.g === 'm') return person.acc
      if (person && (x === 'ее' || x === 'её') && person.g === 'f') return person.acc
      if (!person && thing && x === 'его') return thing
      return w
    })
    .join(' ')
}

/** «Купить продукты, молоко хлеб яйца» — список к общему слову, а не новые дела */
const GENERIC = /\s(?:продукты|продуктов|покупки|вещи|еду|лекарства|документы|подарки|материалы|канцелярию|канцтовары)$/i

/** названия, которые пишут с большой буквы */
const PROPER: [RegExp, string][] = [
  [/(^|\s)мфц(?=\s|$)/gi, '$1МФЦ'], [/(^|\s)гибдд(?=\s|$)/gi, '$1ГИБДД'], [/(^|\s)жкх(?=\s|$)/gi, '$1ЖКХ'], [/(^|\s)фнс(?=\s|$)/gi, '$1ФНС'],
  [/(^|\s)озон(а|е|у)?(?=\s|$)/gi, '$1Озон$2'], [/(^|\s)авито(?=\s|$)/gi, '$1Авито'], [/(^|\s)питер(а|е|у)?(?=\s|$)/gi, '$1Питер$2'],
  [/(^|\s)москв(а|у|е|ы)(?=\s|$)/gi, '$1Москв$2'], [/(^|\s)икеи(?=\s|$)/gi, '$1ИКЕИ'], [/(^|\s)икея(?=\s|$)/gi, '$1ИКЕА'],
  [/(^|\s)вб(?=\s|$)/gi, '$1ВБ'], [/(^|\s)ватсап(?=\s|$)/gi, '$1WhatsApp'],
]
const proper = (t: string) => PROPER.reduce((x, [re, to]) => x.replace(re, to), t)

export function compile(text: string): string[] {
  const out: string[] = []
  const seen = new Set<string>()
  let lastVerb: string | null = null
  let person: Person | null = null
  // список после голого глагола ещё продолжается
  let listOpen = false
  let thing: string | null = null
  const push = (raw: string) => {
    const t = proper(resolve(raw, person, thing))
    const k = low(t).replace(/[^\p{L}\p{N}]+/gu, ' ').trim()
    if (!k || seen.has(k) || out.length >= MAX) return
    seen.add(k)
    out.push(cap(t))
    person = personIn(t) ?? person
    // вещь для «его»: дополнение после глагола, если оно короткое и без предлога
    // «Продать старый велик на Авито» → «старый велик»: слова после глагола до первого предлога
    const ws = t.split(' ').slice(1)
    const cut = ws.findIndex((w) => /^(?:в|во|на|к|ко|с|со|по|для|из|от|у|о|об|за|до|под|через)$/i.test(w))
    const obj = (cut < 0 ? ws : ws.slice(0, cut)).join(' ')
    thing = obj && obj.split(' ').length <= 3 && !personIn(obj) && !/\d/.test(obj) ? low(obj) : null
  }
  for (const raw of text.slice(0, 4000).split(HARD)) {
    for (const piece of splitAnd(raw ?? '')) {
      const pre = tidy(piece).replace(/^(?:а|и|ну)\s+/i, '')
      const open = listOpen
      listOpen = false
      if (REASON.test(pre)) continue
      const s = strip(piece)
      if (s.length < 2 || NOT_A_TASK.test(s)) continue
      const complaint = COMPLAINTS.find(([re]) => re.test(s))
      if (complaint) {
        const obj = s.replace(complaint[0], '$1')
        push(`${complaint[1]} ${accusative(obj)}`)
        lastVerb = null
        continue
      }
      const action = asAction(s) ?? undone(s)
      if (action) {
        lastVerb = action.split(' ')[0]
        push(action)
        continue
      }
      const base = fromBase(s)
      if (base) {
        lastVerb = null
        push(base)
        continue
      }
      const prev = out[out.length - 1]
      // «надо купить: хлеб, сыр, колбасу» — голый глагол и за ним список: одно дело «Купить хлеб, сыр, колбасу»
      if (prev && lastVerb && bareObject(s) && (low(prev) === lastVerb || open)) {
        out[out.length - 1] = low(prev) === lastVerb ? `${prev} ${s}` : `${prev}, ${s}`
        seen.add(low(out[out.length - 1]))
        listOpen = true
        continue
      }
      if (prev && GENERIC.test(prev) && bareObject(s) && s.split(' ').length >= 2) {
        // «Купить продукты» + «молоко хлеб яйца» → «Купить продукты (молоко, хлеб, яйца)»
        out[out.length - 1] = `${prev} (${s.split(' ').join(', ')})`
        continue
      }
      if (lastVerb && bareObject(s)) push(`${lastVerb} ${s}`)
      // своё слово, которого база не знает («таблица», «квартальный отчёт»): дело человека — оставляем как есть;
      // рассказ («зуб болит», «у Лены день рождения») — не дело
      else if (bareObject(s) && !/^у\s/i.test(s)) push(s)
    }
  }
  return out
}
