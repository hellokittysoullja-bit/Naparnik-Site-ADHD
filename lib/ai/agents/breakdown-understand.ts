/** варианты неопределённой формы для слова, которого нет в базе; vocabVerbs — глаголы, которые есть в названиях дел */
export function verbCandidates(w: string, vocabVerbs: ReadonlySet<string>): string[] {
  const out = new Set<string>()
  for (const [re, to] of VERB_RULES) if (re.test(w)) {
    const c = w.replace(re, to)
    if (vocabVerbs.has(c)) out.add(c)
  }
  return [...out]
}
