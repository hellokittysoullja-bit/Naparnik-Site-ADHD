/**
 * Учебная фраза своими словами → как названы дела базы (см. выше). Возвращает слова и для каждого — какие слова фразы он
 * заменил ([с, до)), или null, если фраза не учебная или менять нечего.
 */
export function studyRewrite(tw: readonly string[]): { w: string; from: number; to: number }[] | null {
  const out: { w: string; from: number; to: number }[] = []
  for (let i = 0; i < tw.length; ) {
    const ph = HOMEWORK_PHRASES.find(([p]) => p.every((x, k) => tw[i + k] === x))
    if (ph) {
      out.push({ w: ph[1], from: i, to: i + ph[0].length })
      i += ph[0].length
    } else {
      out.push({ w: tw[i], from: i, to: i + 1 })
      i++
    }
  }
  // предмет после предлога: «к истории» → «по истории», «по англу» → «по английскому»
  let subject = false
  for (let k = 0; k + 1 < out.length; k++) {
    const s = SUBJECT_PREPS.has(out[k].w) ? subjectOf(out[k + 1].w) : null
    if (!s) continue
    subject = true
    out[k] = { ...out[k], w: 'по' }
    out[k + 1] = { ...out[k + 1], w: s }
    // «английскому языку» → «английскому» (так названы дела), «окружающему миру»: хвост в форме после «по»
    const tail = out[k + 2]?.w
    if (tail && /^язык[ауе]?$/.test(tail)) out.splice(k + 1, 2, { w: s, from: out[k + 1].from, to: out[k + 2].to })
    if (s === 'окружающему' && tail && /^мир[ауе]?$/.test(tail)) out[k + 2] = { ...out[k + 2], w: 'миру' }
  }
  if (subject) for (let k = 0; k < out.length; k++) if (TASK_WORDS.has(out[k].w)) out[k] = { ...out[k], w: 'домашку' }
  if (!out.some((t) => STUDY_HEADS.has(t.w))) return null
  const head = out.findIndex((t) => HOMEWORK_HEADS.has(t.w))
  if (head >= 0) {
    for (let k = 0; k < out.length; k++) if (HOMEWORK_VERBS[out[k].w]) out[k] = { ...out[k], w: HOMEWORK_VERBS[out[k].w] }
    // домашка без глагола — «сделать домашку»: «дз по англу» → «Сделать домашку по английскому»
    if (!out.some((t) => /(ть|ться|ти|чь)$/.test(t.w))) out.unshift({ w: 'сделать', from: out[head].from, to: out[head].to })
  }
  const same = out.length === tw.length && out.every((t, k) => t.w === tw[k])
  return same ? null : out
}

