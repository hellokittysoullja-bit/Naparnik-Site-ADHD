import { personaBase } from '@/lib/companion'

/**
 * Характер кота — один источник для всех каналов (personaBase в lib/companion.ts) + ярусы как у Hermes
 * (prompt-assembly): сначала неизменное (личность и правила), затем задача, затем режим аудитории. Изменчивые данные
 * человека в системный промпт не попадают — они идут сообщением (context.ts). Стабильный префикс кэшируется провайдером.
 */
export type Audience = 'adult' | 'minor' | 'unknown'

// Решение владельца 11.11: ИИ отвечает всем, не только 18+. Для младших — бережнее (DeepSeek: до 18 — с согласия
// взрослого; AnyModel «сознательно не собирает» данные младше 18 — отсюда никаких личных фактов в ответах и памяти).
const MINOR = `Собеседнику меньше 18. Говори ещё проще и мягче. Не обсуждай отношения, внешность, вес, еду и диеты, алкоголь, деньги и долги. Не проси и не запоминай личные данные (полное имя, школу, адрес, телефон). На любые темы про здоровье и лекарства — «это лучше обсудить со взрослым, которому доверяешь, или с врачом». Если тяжело — предложи поговорить со взрослым рядом.`

export function systemFor(taskSystem: string, audience: Audience): string {
  return [personaBase, taskSystem, audience === 'minor' ? MINOR : ''].filter(Boolean).join('\n\n')
}
