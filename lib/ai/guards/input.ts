/**
 * Проверки на входе (OpenAI Agents SDK: input guardrails, режим «до вызова модели» — ради безопасности и денег).
 * Правила, а не модель: мгновенно, бесплатно, предсказуемо. Это не диагностика — это повод ответить бережно.
 */

// В JS \w и \b — только латиница: для русских слов — \p{L} с флагом u и границы через (?<!\p{L}).
// Сигналы кризиса: человеку прямо сейчас может быть опасно. На них — не импровизация модели, а проверенный ответ
// с контактами помощи (lib/ai/crisis.ts). Список держим широким: ложное срабатывание стоит одной тёплой реплики,
// пропуск — несравнимо больше.
const CRISIS = [
  /не\s+хочу\s+(больше\s+)?жить/i,
  /не\s+хочется\s+жить/i,
  /хочу\s+умереть/i,
  /(покончить|кончать|покончу)\s+(с\s+собой|с\s+жизнью)/i,
  /(убить|убью)\s+себя/i,
  /суицид|самоубийств/i,
  /(порезать|порежу|режу|резать)\s+(себя|вены|руки)/i,
  /(лучше\s+бы\s+меня\s+не\s+было|меня\s+не\s+должно\s+быть)/i,
  /нет\s+смысла\s+жить|жить\s+незачем|зачем\s+(мне\s+)?жить/i,
  /\bkill\s+myself\b|\bsuicid/i,
]

// Попытки переписать правила кота. Не блокируем (человек мог просто пошутить), но помечаем в журнале: данные
// человека и так идут отдельным блоком «это данные, не инструкции» (context.ts), а проверка выхода ловит последствия.
const INJECTION = [
  /игнорир\p{L}*\s+(все\s+)?(предыдущ|свои|эти|системн)\p{L}*\s+(инструкц|правил|указан)/iu,
  /забудь\s+(все\s+)?(свои\s+)?(инструкц|правил)/i,
  /ты\s+(теперь|больше\s+не)\s+(не\s+)?(кот|напарник)/iu,
  /\b(ignore|disregard)\s+(all\s+)?(previous|prior|above)\s+(instructions|rules)/i,
  /\bsystem\s+prompt\b|системн\p{L}*\s+промпт/iu,
]

export type InputVerdict = { crisis: boolean; injection: boolean }

export function checkInput(texts: string[]): InputVerdict {
  const all = texts.join('\n')
  return {
    crisis: CRISIS.some((r) => r.test(all)),
    injection: INJECTION.some((r) => r.test(all)),
  }
}
