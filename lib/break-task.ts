/**
 * Одно правило разламывания на весь продукт (16.11, владелец: «разламывание везде одинаково и правильно»).
 * Дом, Фокус, «Дела» и «Не могу начать» решают, можно ли разламывать дело, этой функцией; сервер (/api/breakdown)
 * отклоняет дело короче тех же 3 знаков. Раньше порогов было три: Дом — любой текст, Фокус — 8 знаков, сервер — 3,
 * и «Разломать на шаг» с коротким делом молча открывал обычный выбор шага (скриншот владельца 16.11, «Hh»).
 */
export const BREAK_MIN = 3

/** Дело, которое можно отдать на разламывание: не короче 3 знаков и хотя бы две буквы («ок», «2+2» — нет; «пол» — да) */
export function breakable(text: string): boolean {
  const t = text.trim()
  return t.length >= BREAK_MIN && (t.match(/\p{L}/gu)?.length ?? 0) >= 2
}

/** Реплика кота, когда разламывать нечего: не ошибка, а просьба сказать словами */
export const BREAK_TOO_SHORT = 'Напиши хоть пару слов, что висит. Тогда разломаю'
/** Реплика кота, когда модель не поняла дело (набор букв, опечатка): честно, без общих шагов «для любого дела» */
export const BREAK_UNCLEAR = 'Не понял дело. Напиши *словами*, что висит, и разломаю'
