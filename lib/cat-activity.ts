import type { DollActivity } from '@/lib/rig/doll'

/**
 * Чем занят кот рядом во время сессии (владелец 22.11, «работаем вместе»): дело про чтение и учёбу — книга, остальное
 * — ноутбук. По словам самого дела, без вопросов человеку
 */
const BOOK = /(чита|прочит|книг|учебник|конспект|параграф|учи(ть|м)|выучи|повтор|экзамен|зачёт|зачет|сесси|домашк|(?<![а-яё])дз(?![а-яё])|урок|лекци|билет|стих|словар|формул|подготов)/i

export function catActivity(task: string): DollActivity {
  return BOOK.test(task) ? 'book' : 'laptop'
}
