import { useLayoutEffect } from 'react'

/**
 * Первый кадр экрана, чьё содержимое живёт только на устройстве (Фокус, знакомство, «Не могу начать», переписка, «Дела»,
 * Мир), — сразу готовый (16.11, владелец: «с первой миллисекунды то, что нужно»). В HTML такого экрана нет его
 * содержимого — только каркас, и раньше при обновлении человек видел пустоту или заглушку, а потом экран.
 *
 * Скрипт первого кадра (lib/app-prepaint.ts) на этих адресах прячет страницу (`html[data-hold]`, globals.css): пока на
 * ней нет видимого содержимого, браузер не меняет кадр и держит прежний (страницу, с которой пришли, или её же до
 * обновления). Экран снимает запрет этим хуком в момент, когда его настоящее содержимое уже в DOM, — до отрисовки
 * (useLayoutEffect), поэтому первый показанный кадр — готовый экран. Если код не загрузился, запрет снимает сам скрипт
 * через HOLD_MS — страница никогда не остаётся скрытой.
 */
export { HOLD_MS, HOLD_ROUTES } from './first-frame-routes'

export function useFirstFrameReady(ready: boolean) {
  useLayoutEffect(() => {
    if (!ready) return
    const w = window as unknown as { __nfReady?: () => void }
    w.__nfReady?.()
  }, [ready])
}
