export const ALL_TEMPLATES: Template[] = TEMPLATE_GROUPS.flatMap((g) => g.items)

const norm = (t: string) => t.toLowerCase().replace(/ё/g, 'е').replace(/[^\p{L}\s]/gu, ' ').replace(/\s+/g, ' ').trim()

/** Дело из поля совпало с готовым («помыть посуду») — шаги есть сразу, без запроса к ИИ */
export function findTemplate(task: string): Template | null {
  const t = norm(task)
  if (t.length < 4) return null
  return ALL_TEMPLATES.find((x) => norm(x.title) === t) ?? null
}
