/* ── Симметричные гладкие формы ─────────────────────────────────────── */

type Pt = readonly [number, number];
type Seg = readonly [Pt, Pt, Pt]; // c1, c2, конец кубической кривой

/**
 * Гладкий симметричный силуэт: правая половина задаётся кубическими
 * кривыми сверху вниз (от центральной оси x=100), левая — её зеркало.
 * Чиби-маскоты уровня Duolingo держатся на мягких, непрерывных формах:
 * ни одного случайного зубца, пушистость — 2–3 крупных округлых пучка.
 */
function mirrored(top: Pt, right: Seg[]) {
  const f = (v: number) => +v.toFixed(2);
  const m = (p: Pt): Pt => [200 - p[0], p[1]];
  let d = `M${f(top[0])} ${f(top[1])}`;
  for (const [a, b, c] of right) d += ` C${a.map(f)} ${b.map(f)} ${c.map(f)}`.replace(/,/g, " ");
  const pts: Pt[] = [top, ...right.map((r) => r[2])];
  for (let i = right.length - 1; i >= 0; i--) {
    const [a, b] = right[i];
    const start = pts[i];
    d += ` C${m(b).map(f)} ${m(a).map(f)} ${m(start).map(f)}`.replace(/,/g, " ");
  }
  return `${d}Z`;
}

/* ── Пушистая кромка ───────────────────────────────────────────────── */

/**
 * Пряди-«запятые» по краю силуэта: у каждой гладкое основание, утопленное
 * в форму, и мягко изогнутый кончик, зачёсанный вдоль касательной. Рисуются
 * общим проходом с основной формой (сначала все обводки, потом все
 * заливки), поэтому контур получается единым пушистым силуэтом без швов —
 * пушистость референса, но гладкая, «маскотная», без зубцов пилы.
 *
 * spec: [угол в градусах (0 = вправо, 90 = вниз), длина, полуширина, зачёс]
 */
export function fringe(
  cx: number,
  cy: number,
  rx: number,
  ry: number,
  spec: ReadonlyArray<readonly [number, number, number, number]>,
) {
  const f = (v: number) => v.toFixed(1);
  return spec.map(([deg, len, w, sweep]) => {
    const a = (deg * Math.PI) / 180;
    const bx = cx + Math.cos(a) * (rx - 4);
    const by = cy + Math.sin(a) * (ry - 4);
    let nx = Math.cos(a) / rx;
    let ny = Math.sin(a) / ry;
    const nl = Math.hypot(nx, ny);
    nx /= nl;
    ny /= nl;
    const tx = -ny;
    const ty = nx;
    const L = len + 4;
    const p1 = [bx - tx * w, by - ty * w];
    const p2 = [bx + tx * w, by + ty * w];
    const tip = [bx + nx * L + tx * sweep * L, by + ny * L + ty * sweep * L];
    const c1 = [p1[0] + nx * L * 0.7 + tx * sweep * L * 0.2, p1[1] + ny * L * 0.7 + ty * sweep * L * 0.2];
    const c2 = [p2[0] + nx * L * 0.35, p2[1] + ny * L * 0.35];
    return `M${f(p1[0])} ${f(p1[1])} Q${f(c1[0])} ${f(c1[1])} ${f(tip[0])} ${f(tip[1])} Q${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}Z`;
  });
}

