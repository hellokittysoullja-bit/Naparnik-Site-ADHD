/** Детерминированный «случай»: одинаковые пряди на сервере и клиенте */
function seeded(seed: number) {
  let v = seed;
  return () => {
    v = (v * 16807) % 2147483647;
    return v / 2147483647;
  };
}

/**
 * Раскладка прядей по углам: from..to с шагом, длина и зачёс по функции
 * угла, плюс небольшой разброс — мех живой, а не «расчёска».
 */
function furSpec(
  seed: number,
  ranges: ReadonlyArray<readonly [number, number, number]>,
  len: (deg: number) => number,
  width = 5.5,
) {
  const r = seeded(seed);
  const out: Array<[number, number, number, number]> = [];
  for (const [from, to, step] of ranges) {
    for (let a = from; a <= to; a += step) {
      const deg = a + (r() - 0.5) * step * 0.5;
      const right = Math.cos((deg * Math.PI) / 180) >= 0;
      out.push([
        deg,
        len(deg) * (0.75 + r() * 0.5),
        width * (0.8 + r() * 0.4),
        (right ? 1 : -1) * (0.45 + r() * 0.3),
      ]);
    }
  }
  return out;
}

