/**
 * Вернувшийся человек — сразу домой, как у Duolingo: открыл сайт через неделю или через год — он в своём доме, а не
 * на лендинге или в знакомстве заново. Память живёт на устройстве, поэтому решение принимает встроенный скрипт
 * ДО первой отрисовки: страница прячется (виден только фон сайта) и заменяется на /app — без кадра лендинга и без
 * лишней записи в истории (кнопка «назад» не вернёт на лендинг).
 *
 * Скрипт работает только при загрузке страницы с сервера: при переходе внутри сайта (например, «Назад» на первом
 * вопросе знакомства ведёт на лендинг) React вставленные так скрипты не выполняет — человек увидит то, куда шёл.
 * `?intro=1` в адресе — посмотреть лендинг, даже если старты уже есть.
 */
const SCRIPT = `try{var s=JSON.parse(localStorage.getItem("naparnik:starts")||"[]");if(Array.isArray(s)&&s.length>0&&!/[?&]intro(=|&|$)/.test(location.search)){document.documentElement.style.visibility="hidden";location.replace("/app")}}catch(e){}`

export function ReturningRedirect() {
  return <script dangerouslySetInnerHTML={{ __html: SCRIPT }} />
}
