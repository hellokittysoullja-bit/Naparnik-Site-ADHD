/**
 * Первый кадр лендинга — сразу в финальной раскладке. HTML приходит по сети порциями, и браузер рисует то, что
 * успело прийти: в кадре оказывались кот, заголовок и кнопка, а реплики и чипов ещё не было. Колонка героя
 * центрирована по высоте, поэтому без нижнего блока кот вставал почти посередине экрана (y=160 вместо 58 на
 * 390×664) и прыгал на место, когда долетал остаток HTML (замер 27.10, 4G + CPU ×4; владелец увидел это на телефоне).
 *
 * Второе условие — вшитые шрифты первого экрана: пока браузер их разбирает (кадр-два), невидимый текст раскладывается
 * по запасному шрифту, и рукописная строка «даже если ты пропал на неделю» переносилась на лишнюю строку — колонка
 * становилась выше, и кот стоял на 7 px выше места. Текст всё равно невидим до шрифта (font-display: block), так что
 * ожидание прячет только этот неверный кадр.
 *
 * HeroWait — до сцены: прячет её и сразу запускает разбор вшитых шрифтов. HeroReady — сразу после сцены: парсер
 * доходит до него, когда сцена получена целиком; показываем, как только готовы и шрифты. Без JS класс не ставится;
 * страховка 1,5 с — если что-то пойдёт не так, сцена всё равно покажется.
 */
// Вшитые начертания (data: URI) отличаем по unicode-range: design/fonts/build.py собирает их ровно под символы
// первого экрана, и диапазон начинается с пробела и «!» (U+20-21). У внешних файлов такого нет (кириллица — U+20-40,
// латиница — без пробела); их ждать нельзя — это сеть. Разбор вшитых запускаем сразу, ещё до раскладки.
const WAIT = `(function(){var d=document.documentElement,f=document.fonts,w=[];d.classList.add("hero-wait");if(f&&f.forEach)f.forEach(function(x){var n=x.family.replace(/["']/g,"");if((n==="Manrope"||n==="Caveat")&&/U\\+20-21(,|$)/i.test(x.unicodeRange))w.push(x.load())});window.__heroFonts=Promise.all(w).catch(function(){});setTimeout(function(){d.classList.remove("hero-wait")},1500)})()`
const READY = `(window.__heroFonts||Promise.resolve()).then(function(){document.documentElement.classList.remove("hero-wait")})`

export function HeroWait() {
  return <script dangerouslySetInnerHTML={{ __html: WAIT }} />
}

export function HeroReady() {
  return <script dangerouslySetInnerHTML={{ __html: READY }} />
}
