def fix_time(t, st, mm):
    out_s, out_m = [], []
    for s, m in zip(st, mm):
        if s.startswith('Время от времени '):
            rest = s[len('Время от времени '):]
            o = next((v for (tt, pre), v in OVR.items() if tt == t and rest.startswith(pre)), 0)
            if o is None: LOG['вода'].append(f'{t}: {s}'); continue
            if o: LOG['время'].append(f'{t}: {s} → {o}'); out_s.append(o); out_m.append(m); continue
            if WATER.search(rest) and len(st) > 3: LOG['вода'].append(f'{t}: {s}'); continue
            pre = next((p for rx, p in FREQ if re.match(rx, rest)), None)
            ns = (pre + rest) if pre else cap(rest)
            LOG['время'].append(f'{t}: {s} → {ns}'); s = ns
        out_s.append(s); out_m.append(m)
    return out_s, out_m

