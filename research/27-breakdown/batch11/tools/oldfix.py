    st2, mm2 = fix_time(t, st, mm); st2, mm2 = fix_buy(t, st2, mm2)
    if st2 == st: return mo.group(0)
    mins[t] = mm2
    return f'  {q(t)}: [{", ".join(q(s) for s in st2)}],'
