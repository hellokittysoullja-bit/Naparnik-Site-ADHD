# дубли внутри партии: подмена глагола из той же группы (как filt.mts) и одинаковые основы слов
import re, itertools
G = [['Найти', 'Вызвать', 'Выбрать', 'Подобрать'], ['Оформить', 'Открыть', 'Сделать', 'Получить'], ['Отнести', 'Отправить', 'Сдать', 'Отвезти', 'Отдать'], ['Подготовить', 'Собрать', 'Устроить', 'Организовать'], ['Обновить', 'Поменять', 'Сменить', 'Заменить'], ['Научиться', 'Освоить', 'Выучить', 'Изучить'], ['Перестать', 'Бросить', 'Справиться с'], ['Настроить', 'Включить', 'Подключить', 'Установить', 'Поставить'], ['Помыть', 'Почистить', 'Вымыть', 'Отмыть', 'Протереть'], ['Сходить к', 'Записаться к', 'Сходить на', 'Записаться на', 'Сделать'], ['Сходить в', 'Съездить в', 'Записаться в'], ['Купить', 'Выбрать', 'Заказать'], ['Убрать', 'Разобрать'], ['Починить', 'Поменять'], ['Сдать', 'Сделать', 'Пройти'], ['Удалить', 'Убрать'], ['Восстановить', 'Вернуть'], ['Оплатить', 'Заплатить за'], ['Забронировать', 'Заказать', 'Сделать бронь'], ['Пожарить', 'Приготовить', 'Сварить', 'Испечь', 'Запечь', 'Сделать'], ['Сводить', 'Отвезти', 'Отвести'], ['Начать', 'Научиться']]
tasks=[l for l in open('tasks.txt').read().split('\n') if l]
st=lambda s: ' '.join(sorted(w[:max(3,min(5,len(w)-2))] for w in re.findall(r'[а-яёa-z0-9]{3,}', s.lower())))
idx={}
for t in tasks: idx.setdefault(t.lower(), t)
seen=set()
for t in tasks:
    for g in G:
        for a in g:
            if t.startswith(a+' '):
                for b in g:
                    if b==a: continue
                    o=b+t[len(a):]
                    if o.lower() in idx and (o,t) not in seen: seen.add((t,o)); print(f'{t}  ==  {o}')
bys={}
for t in tasks: bys.setdefault(st(t),[]).append(t)
for k,v in bys.items():
    if len(v)>1: print('основы:', ' | '.join(v))
