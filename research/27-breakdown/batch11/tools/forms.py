# Формулировки дел существительным (владелец 21.11: «в разных словосочетаниях, разными способами постановки»):
# «Помыть духовку» → «Мытьё духовки», «Записаться к стоматологу» → «Запись к стоматологу», «Позвонить маме» → «Звонок маме».
# Падежи — pymorphy3 (словарь OpenCorpora), не правила на глаз. Вход: названия дел по строке; выход: «форма<TAB>дело».
import sys, re, pymorphy3
m = pymorphy3.MorphAnalyzer()
NOUN = {
 'Помыть': 'Мытьё', 'Вымыть': 'Мытьё', 'Почистить': 'Чистка', 'Постирать': 'Стирка', 'Погладить': 'Глажка', 'Купить': 'Покупка',
 'Починить': 'Ремонт', 'Отремонтировать': 'Ремонт', 'Поменять': 'Замена', 'Заменить': 'Замена', 'Сменить': 'Смена', 'Установить': 'Установка',
 'Настроить': 'Настройка', 'Оформить': 'Оформление', 'Разморозить': 'Разморозка', 'Удалить': 'Удаление', 'Обновить': 'Обновление',
 'Восстановить': 'Восстановление', 'Отменить': 'Отмена', 'Вернуть': 'Возврат', 'Оплатить': 'Оплата', 'Посадить': 'Посадка',
 'Забронировать': 'Бронирование', 'Проверить': 'Проверка', 'Заказать': 'Заказ', 'Отправить': 'Отправка', 'Заполнить': 'Заполнение',
 'Покрасить': 'Покраска', 'Подстричь': 'Стрижка', 'Перенести': 'Перенос', 'Подготовить': 'Подготовка', 'Найти': 'Поиск',
 'Выбрать': 'Выбор', 'Посчитать': 'Подсчёт', 'Открыть': 'Открытие', 'Закрыть': 'Закрытие', 'Распечатать': 'Распечатка',
 'Поклеить': 'Поклейка', 'Продлить': 'Продление', 'Получить': 'Получение', 'Сдать': 'Сдача', 'Утеплить': 'Утепление',
 'Прочистить': 'Прочистка', 'Перевести': 'Перевод', 'Отпарить': 'Отпаривание', 'Заклеить': 'Заклейка', 'Пройти': 'Прохождение',
}
KEEP = {'Записаться': 'Запись', 'Подготовиться': 'Подготовка', 'Позвонить': 'Звонок', 'Съездить': 'Поездка'}
PREP = {'в', 'во', 'на', 'к', 'ко', 'с', 'со', 'для', 'от', 'по', 'из', 'у', 'за', 'под', 'после', 'до', 'перед', 'о', 'об', 'через', 'без', 'при', 'и'}
OBJ_POS = {'NOUN', 'ADJF', 'PRTF', 'NPRO', 'NUMR'}
# вещи, у которых «сборка» звучит естественно; «Собрать чемодан» → «Сборка чемодана» — нет
FURN = re.compile(r'шкаф|кроват|стол|стул|кресл|комод|тумб|стеллаж|полк|кухн|диван|манеж|компьютер|велосипед|батут|теплиц|мебел|коляск')
GENT_FIX = {'цветы': 'цветов'}  # словарь считает «цветы» множественным от «цветок»
SMENA = re.compile(r'^(причёск|прическ|работ|професс|фамил|им[яе]|тариф|банк|оператор|мастер|врач|поликлиник|школ|садик|парикмахер|парол|аватар|прописк|страхов|терапевт|мест|город|квартир|номер|имидж|стил|режим|обстановк|дизайн|интерьер|гардероб|круг|окружени|привычк|расписани|график|подход)')
def _cap(src, w): return w[0].upper() + w[1:] if src[0].isupper() else w
VERB = ''
def np_gent(obj):
    """винительный → родительный у главного существительного и прилагательных перед ним; всё после главного слова
    («работу мечты», «анализ крови», «приложение банка») уже в своём падеже и не трогается"""
    isn = lambda w: any(p.tag.POS == 'NOUN' and 'accs' in p.tag for p in m.parse(w))
    isa = lambda w: any(p.tag.POS in ('ADJF', 'PRTF') for p in m.parse(w))
    # «белые вещи»: «белые» тоже бывает существительным — главное слово первое, которое не прилагательное
    head = next((k for k, w in enumerate(obj) if isn(w) and not isa(w)), None)
    if head is None: head = next((k for k, w in enumerate(obj) if isn(w)), None)
    if head is None:
        return None
    hp = next(p for p in m.parse(obj[head]) if p.tag.POS == 'NOUN' and 'accs' in p.tag)
    # слова нет в словаре (pymorphy угадывает по окончанию: «кофемашину» → «кофемашиной») — формулировку не делаем
    if not hp.is_known: return None
    # «Погладить кота» — приласкать, не утюг
    if VERB == 'Погладить' and 'anim' in hp.tag: return None
    num = 'plur' if 'plur' in hp.tag else 'sing'
    out = []
    for k, w in enumerate(obj):
        if k > head or re.match(r'^[A-Za-z0-9]', w) or (w.isupper() and len(w) > 1):
            out.append(w); continue
        if k == head:
            if w.lower() in GENT_FIX: out.append(_cap(w, GENT_FIX[w.lower()])); continue
            g = hp.inflect({'gent', num})
        else:
            ps = [p for p in m.parse(w) if 'accs' in p.tag and p.tag.POS in ('ADJF', 'PRTF', 'NPRO', 'NUMR') and num in p.tag and (num == 'plur' or hp.tag.gender in p.tag)]
            if not ps: return None
            g = ps[0].inflect({'gent', num} | ({hp.tag.gender} if num == 'sing' and hp.tag.gender else set()))
        if not g: return None
        out.append(_cap(w, g.word))
    return out
def nominal(t):
    ws = t.split(' ')
    v, rest = ws[0], ws[1:]
    if v in KEEP: return [f'{KEEP[v]} {" ".join(rest)}'] if rest else []
    n = NOUN.get(v) or ('Сборка' if v == 'Собрать' and FURN.search(t) else None)
    # «Поменять причёску» — смена, «Поменять батарейки» — замена
    if v in ('Поменять', 'Сменить', 'Заменить') and rest and SMENA.search(rest[0].lower()): n = 'Смена'
    if not n or not rest: return []
    obj, k = [], 0
    while k < len(rest) and rest[k].lower() not in PREP: obj.append(rest[k]); k += 1
    if not obj: return []
    global VERB
    VERB = v
    g = np_gent(obj)
    if not g: return []
    return [' '.join([n, *g, *rest[k:]])]
if __name__ == '__main__':
    for t in open(sys.argv[1]).read().split('\n'):
        if t:
            for f in nominal(t): print(f'{f}\t{t}')
